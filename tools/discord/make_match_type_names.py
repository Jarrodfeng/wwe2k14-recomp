"""Session 33 (Discord status): write src/match_type_names.h from db/ids/match_types.json (our own id table, made
from the PLAY menus in Session 30). The display name is the menu path after PLAY, without SPECIALTY and a last NORMAL,
in title case: "PLAY > TWO ON TWO > TORNADO TAG > HELL IN A CELL" -> "Two on Two - Tornado Tag - Hell in a Cell".
Run: py tools/discord/make_match_type_names.py"""
import json, os

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SMALL = {'ON', 'A', 'IN', 'OF', 'THE'}


def title(seg):
    words = seg.split()
    out = []
    for i, w in enumerate(words):
        if w in ('TLC', 'I'):
            out.append(w)
        elif i and w in SMALL:
            out.append(w.lower())
        else:
            out.append('-'.join(p.capitalize() for p in w.split('-')))
    return ' '.join(out)


def main():
    d = json.load(open(os.path.join(REPO, 'db', 'ids', 'match_types.json'), encoding='utf-8'))
    rows = []
    for e in d['entries']:
        segs = [s.strip() for s in e['menu_paths'][0].split('>')][1:]
        segs = [s for s in segs if s != 'SPECIALTY']
        if len(segs) > 1 and segs[-1] == 'NORMAL':
            segs = segs[:-1]
        rows.append((e['id'], ' - '.join(title(s) for s in segs)))
    lines = ['// Generated by tools/discord/make_match_type_names.py from db/ids/match_types.json (Session 33). Do not edit.',
             '#pragma once', '', '#include <cstdint>', '', 'namespace wwe2k14::match_types {', '',
             'struct Name {', '  uint32_t id;', '  const char* text;', '};', '',
             'inline constexpr Name kNames[] = {']
    for i, t in rows:
        lines.append('    {%d, "%s"},' % (i, t))
    lines += ['};', '', 'inline const char* NameOf(uint32_t id) {', '  for (const Name& n : kNames)',
              '    if (n.id == id) return n.text;', '  return nullptr;', '}', '', '}  // namespace wwe2k14::match_types', '']
    open(os.path.join(REPO, 'src', 'match_type_names.h'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print(f'{len(rows)} match types -> src/match_type_names.h')


if __name__ == '__main__':
    main()
