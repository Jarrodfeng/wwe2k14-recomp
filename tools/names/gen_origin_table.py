r"""S101 renderer names: db\ids\origin_table.json -> src\renderer_adapter\origin_table.h (the declared map from a submit function to its draw
class and technique, with each function's bounds from the q index).

  py -I tools\names\gen_origin_table.py [--check]

--check: exit 1 if the header is not what the json gives (the gate runs this). Function bounds: `py tools\q\q.py fn ADDR` ("size N").
Writes only our annotations (addresses, class names, technique names): no game code.
"""
import json, re, subprocess, sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / 'db' / 'ids' / 'origin_table.json'
OUT = REPO / 'src' / 'renderer_adapter' / 'origin_table.h'
CLASSES = ['unnamed', 'model_part', 'crowd', 'sprite', 'text', 'movie', 'particle', 'shadow', 'post', 'clear', 'other']
ENUM = {n: 'DrawClass::' + ''.join(p.capitalize() for p in n.split('_')) for n in CLASSES}


def fn_size(addr):
    p = subprocess.run([sys.executable, '-I', str(REPO / 'tools' / 'q' / 'q.py'), 'fn', addr], capture_output=True, text=True, cwd=REPO)
    m = re.search(r'size (\d+)', p.stdout)
    if not m:
        raise SystemExit(f'gen_origin_table: no size for {addr} from q.py fn (output: {p.stdout[:200]!r} {p.stderr[:200]!r})')
    return int(m.group(1))


def build():
    data = json.loads(SRC.read_text(encoding='utf-8'))
    rows = []
    for kind in ('passes', 'submitters'):
        for e in data[kind]:
            if e['class'] not in ENUM:
                raise SystemExit(f"gen_origin_table: unknown class {e['class']!r} for {e['fn']}")
            start = int(e['fn'], 16)
            rows.append((kind, start, start + fn_size(e['fn']), e['class'], e.get('technique', '')))
    lines = [
        '// GENERATED by tools\\names\\gen_origin_table.py from db\\origin_table.json (S101 renderer names). Our annotations only. Do not edit.',
        '// Which submit function a draw came from -> its class and technique. Bounds [start, end) from the q index.',
        '#pragma once',
        '#include <cstdint>',
        '#include "names.h"',
        '',
        'namespace rdr_adapter::origin {',
        '',
        'struct FnRow { uint32_t start, end; DrawClass klass; const char* technique; };',
        '',
    ]
    for kind in ('passes', 'submitters'):
        name = 'kPasses' if kind == 'passes' else 'kSubmitters'
        sel = sorted((r for r in rows if r[0] == kind), key=lambda r: r[1])
        lines.append(f'inline constexpr FnRow {name}[] = {{')
        for _, s, e, c, t in sel:
            lines.append(f'    {{0x{s:08X}u, 0x{e:08X}u, {ENUM[c]}, "{t}"}},')
        lines.append('};')
        lines.append('')
    lines += [
        '// The row whose function holds `site`, or nullptr. The tables are short (tens of rows): a linear scan.',
        'template <size_t N>',
        'inline const FnRow* FindRow(const FnRow (&rows)[N], uint32_t site) {',
        '  for (const FnRow& r : rows)',
        '    if (site >= r.start && site < r.end) return &r;',
        '  return nullptr;',
        '}',
        '',
        '}  // namespace rdr_adapter::origin',
        '',
    ]
    return '\n'.join(lines)


ROLES_SRC = REPO / 'db' / 'ids' / 'surface_roles.json'
ROLES_OUT = REPO / 'src' / 'renderer_adapter' / 'surface_role_table.h'
ROLES = ['unnamed', 'scene_color', 'scene_depth', 'shadow_map', 'post_step', 'feedback_map', 'atlas_target', 'menu_picture', 'tron_picture',
         'ui', 'present', 'other', 'rim_map']  # S101 lane 86: rim_map (names.h SurfaceRole::RimMap)
ROLE_ENUM = {n: 'SurfaceRole::' + ''.join(p.capitalize() for p in n.split('_')) for n in ROLES}


def build_roles():
    data = json.loads(ROLES_SRC.read_text(encoding='utf-8'))
    rows = []
    for e in data['creators']:
        if e['role'] not in ROLE_ENUM:
            raise SystemExit(f"gen_origin_table: unknown role {e['role']!r} for {e['fn']}")
        start = int(e['fn'], 16)
        scale = {True: 'ScaleRule::Yes', False: 'ScaleRule::No', 'screen_shaped': 'ScaleRule::IfScreenShaped'}.get(e['scales'])
        if scale is None:
            raise SystemExit(f"gen_origin_table: scales must be true / false / \"screen_shaped\" for {e['fn']}")
        rows.append((start, start + fn_size(e['fn']), e['role'], scale, bool(e['lasting']), e.get('name', '').replace('"', "'")))
    lines = [
        '// GENERATED by tools\\names\\gen_origin_table.py from db\\ids\\surface_roles.json (S101 renderer names). Our annotations only. Do not edit.',
        '// Which function created a render target -> its role, whether it follows the render scale, whether it lasts across frames.',
        '#pragma once',
        '#include <cstdint>',
        '#include "names.h"',
        '',
        'namespace rdr_adapter::roles {',
        '',
        '// IfScreenShaped: the class makes surfaces of several sizes and which create is which is not read yet (render_targets.md Unknown);',
        '// within its declared role only the screen-shaped ones scale. Yes / No are declared outright.',
        'enum class ScaleRule : uint8_t { No, Yes, IfScreenShaped };',
        'struct CreatorRow { uint32_t start, end; SurfaceRole role; ScaleRule scales; bool lasting; const char* name; };',
        '',
        'inline constexpr CreatorRow kCreators[] = {',
    ]
    for s, e, r, sc, la, n in sorted(rows):
        lines.append(f'    {{0x{s:08X}u, 0x{e:08X}u, {ROLE_ENUM[r]}, {sc}, {str(la).lower()}, "{n}"}},')
    lines += [
        '};',
        '',
        'inline const CreatorRow* FindCreator(uint32_t site) {',
        '  for (const CreatorRow& r : kCreators)',
        '    if (site >= r.start && site < r.end) return &r;',
        '  return nullptr;',
        '}',
        '',
        '}  // namespace rdr_adapter::roles',
        '',
    ]
    return '\n'.join(lines)


def main():
    outputs = [(OUT, build(), 'db\\ids\\origin_table.json'), (ROLES_OUT, build_roles(), 'db\\ids\\surface_roles.json')]
    if '--check' in sys.argv:
        bad = 0
        for out, text, src in outputs:
            old = out.read_text(encoding='utf-8') if out.exists() else ''
            if old.replace('\r\n', '\n') != text:
                print(f'FAIL {out.name} is not what {src} gives: run py -I tools\\names\\gen_origin_table.py')
                bad = 1
        if not bad:
            print('origin_table.h and surface_role_table.h match their json')
        return bad
    for out, text, _ in outputs:
        out.write_text(text, encoding='utf-8', newline='\n')
        print(f'wrote {out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
