#!/usr/bin/env python3
r"""Lint: every live gate check can say what it depends on (S103 lane DIB; docs\research\s103\DI_index_check_selection.md section 4.3).

  py -I tools\gate\deps_lint.py [--root DIR] [--selftest] [--write-legacy]

A check passes when it has (a) an explicit `affects` (check or lane level), or (b) EXACT script-derived dependencies (tier B of tools\gate\deps.py: the script, its
imports and every repo path its code names, nothing scanned), or (c) a `"deps": "scan:<dirs>"` / `"uncacheable": "<reason>"` entry on the check, or (d) is listed in
tools\gate\deps_legacy.txt (the checks that predate this rule: no affects and a SCAN / UNKNOWN / compile-derived dependency set; generated by --write-legacy, may only
shrink). Tier B is the only tier decided from the tree alone (A needs the build manifests / the index of the machine), so the lint gives the same answer everywhere.
A check on none of these FAILs: "name what it reads" (add `affects`, or `"deps": "scan:src"`).
Also: a check whose unit the index parsed with errors (game_syntax) is forced to `affects` (its derived list is partial: the derived set only ever ADDS selection);
a `deps` entry of the wrong form fails; a legacy line for a check that now has affects / is exact / no longer exists is reported stale (remove it).
Retired checks are skipped. Selftest: planted checks of each class."""
import argparse
import json
import re
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import deps as gdeps


def legacy_names(root):
    p = Path(root) / 'tools' / 'gate' / 'deps_legacy.txt'
    if not p.is_file():
        return set()
    return {ln.strip() for ln in p.read_text(encoding='utf-8').splitlines() if ln.strip() and not ln.startswith('#')}


def load_checks(root):
    out = []
    for f in sorted((Path(root) / 'tools' / 'gate' / 'lanes').glob('*.json')):
        try:
            data = json.loads(f.read_text(encoding='utf-8'))
        except Exception:
            continue
        for c in data.get('checks', []):
            c = dict(c)
            c['lane'] = f.stem
            if 'affects' not in c and 'affects' in data:
                c['affects'] = data['affects']
            out.append(c)
    return out


def declared_deps(c):
    """None when the check carries no deps declaration; else a problem text ('' = fine)."""
    if 'deps' not in c and 'uncacheable' not in c:
        return None
    if 'uncacheable' in c:
        return '' if isinstance(c['uncacheable'], str) and c['uncacheable'].strip() else '"uncacheable" needs a reason string'
    v = c.get('deps')
    if isinstance(v, str) and v.startswith('scan:') and v[5:].strip():
        return ''
    return f'"deps" must be "scan:<dirs>" (got {v!r})'


def base_legacy_names(root):
    """The names the legacy list held at its baseline: the merge-base with main when it has the file, else the commit that first added it (the list is born on a
    branch before it reaches main). None when git cannot say (no repo / no history): the shrink-only rule is then not checked, loudly by the caller."""
    import subprocess

    def git(*a):
        p = subprocess.run(['git', '-C', str(root)] + list(a), capture_output=True, text=True, timeout=60)
        return p.stdout if p.returncode == 0 else None
    rel = 'tools/gate/deps_legacy.txt'
    txt = None
    try:   # an explicit baseline: `# baseline-commit: <sha>` in the file's header (the commit whose list is the ceiling; set when the list is frozen)
        m = re.search(r'^# baseline-commit: ([0-9a-f]{7,40})\s*$', (Path(root) / rel).read_text(encoding='utf-8'), re.M)
        if m:
            txt = git('show', f'{m.group(1)}:{rel}')
    except OSError:
        pass
    mb = (git('merge-base', 'HEAD', 'main') or '').strip() if txt is None else ''
    txt = git('show', f'{mb}:{rel}') if mb and txt is None else txt
    if txt is None:
        first = (git('log', '--diff-filter=A', '--format=%H', '--', rel) or '').split()
        txt = git('show', f'{first[-1]}:{rel}') if first else None
    if txt is None:
        return None
    return {ln.strip() for ln in txt.splitlines() if ln.strip() and not ln.startswith('#')}


def lint(root, main=None, checks=None, table=None, base_names=None):
    """base_names: the legacy names at the baseline (S103 DIB2 review bug 11: the list may only SHRINK; a name added since is a failure)."""
    root = Path(root)
    main = Path(main) if main else root
    checks = checks if checks is not None else load_checks(root)
    tb = table or gdeps.Table(root, main, cache_path=root / 'out' / 'gate' / 'deps_lint.json', log=lambda *_a: None)
    legacy = legacy_names(root)
    bad, stale, seen = [], [], set()
    for c in checks:
        if c.get('retired'):
            continue
        name = c['name']
        seen.add(name)
        has_aff = c.get('affects') is not None
        dd = declared_deps(c)
        if dd:
            bad.append(f'{name}: {dd}')
            continue
        d = tb.get(c)
        parsed_err = any('parsed it with errors' in n for n in d['notes'])
        if parsed_err and not has_aff:
            bad.append(f'{name}: a unit the index parsed with errors makes its derived deps partial; declare `affects` (the globs of what it compiles)')
            continue
        static_exact = d['tier'] == 'B' and d['exact']
        if has_aff or dd == '' or static_exact:
            if name in legacy:
                stale.append(f'{name}: has affects / a deps entry / exact script deps now; remove it from tools/gate/deps_legacy.txt')
            continue
        if name in legacy:
            continue
        bad.append(f'{name}: no `affects`, tier {d["tier"]} derived deps ({(d["notes"] or ["not exact"])[0][:70]}): add `affects` globs, or "deps": "scan:<dirs>" if it enumerates a tree')
    for n in sorted(legacy - seen):
        stale.append(f'{n}: in deps_legacy.txt but no live check has that name')
    if base_names is not None:
        for n in sorted(legacy - base_names):
            bad.append(f'{n}: added to tools/gate/deps_legacy.txt since its baseline; the list may only shrink: give the check `affects`, or "deps": "scan:<dirs>"')
    return bad, stale


def write_legacy(root, main=None):
    root = Path(root)
    tb = gdeps.Table(root, main or root, cache_path=root / 'out' / 'gate' / 'deps_lint.json', log=lambda *_a: None)
    names = []
    for c in load_checks(root):
        if c.get('retired') or c.get('affects') is not None or declared_deps(c) == '':
            continue
        d = tb.get(c)
        if not (d['tier'] == 'B' and d['exact']):
            names.append(c['name'])
    (root / 'tools' / 'gate' / 'deps_legacy.txt').write_text(
        '# Checks that predate the deps lint (S103 DIB): no `affects` and a SCAN / UNKNOWN / compile-derived dependency set. Generated by deps_lint.py --write-legacy;\n'
        '# may only shrink. A new check declares `affects`, has exact script deps, or says "deps": "scan:<dirs>".\n' + '\n'.join(sorted(set(names))) + '\n', encoding='utf-8')
    print(f'wrote {len(set(names))} legacy check names')


def selftest():
    d = Path(tempfile.mkdtemp(prefix='deps_lint_'))
    (d / 'tools' / 'gate' / 'lanes').mkdir(parents=True)
    for rel, txt in {'tools/ok.py': "print(open('src/a.h').read())\n", 'tools/scan.py': "import os\nos.walk('src')\n", 'src/a.h': 'x\n'}.items():
        (d / rel).parent.mkdir(parents=True, exist_ok=True)
        (d / rel).write_text(txt)
    L = d / 'tools' / 'gate' / 'lanes'
    chk = [{'name': 'aff', 'cmd': ['py', 'tools/scan.py'], 'affects': ['src/**']},
           {'name': 'exact', 'cmd': ['py', 'tools/ok.py']},
           {'name': 'scan_decl', 'cmd': ['py', 'tools/scan.py'], 'deps': 'scan:src'},
           {'name': 'bare_scan', 'cmd': ['py', 'tools/scan.py']},
           {'name': 'bad_decl', 'cmd': ['py', 'tools/scan.py'], 'deps': 'whatever'},
           {'name': 'old_scan', 'cmd': ['py', 'tools/scan.py']},
           {'name': 'fixed', 'cmd': ['py', 'tools/ok.py']},
           {'name': 'retired_bare', 'cmd': ['py', 'tools/scan.py'], 'retired': 'gone'}]
    (L / 'x.json').write_text(json.dumps({'checks': chk}))
    (d / 'tools' / 'gate' / 'deps_legacy.txt').write_text('old_scan\nfixed\nghost\n')
    bad, stale = lint(d, base_names={'old_scan', 'fixed', 'ghost'})
    names = lambda xs: {x.split(':')[0] for x in xs}
    (d / 'tools' / 'gate' / 'deps_legacy.txt').write_text('old_scan\nfixed\nghost\nbare_scan\n')   # PLANT (bug 11): a name added to the legacy list after its baseline
    bad_added, _s = lint(d, base_names={'old_scan', 'fixed', 'ghost'})
    ok_added = any(x.startswith('bare_scan: added to') for x in bad_added)
    (d / 'tools' / 'gate' / 'deps_legacy.txt').write_text('old_scan\nfixed\nghost\n')
    res = [('a check with affects passes', 'aff' not in names(bad)),
           ('a check with exact script deps passes', 'exact' not in names(bad)),
           ('a "deps": "scan:src" entry passes', 'scan_decl' not in names(bad)),
           ('PLANT: a scanning check with no affects / entry is caught', 'bare_scan' in names(bad)),
           ('PLANT: a malformed deps entry is caught', 'bad_decl' in names(bad)),
           ('a legacy-listed scanner passes', 'old_scan' not in names(bad)),
           ('a retired check is skipped', 'retired_bare' not in names(bad)),
           ('a legacy line for a now-exact check is stale', 'fixed' in names(stale)),
           ('a legacy line for a check that does not exist is stale', 'ghost' in names(stale)),
           ('exactly two bad checks', len(bad) == 2),
           ('PLANT (bug 11): a name added to the legacy list after its baseline fails', ok_added)]
    fail = 0
    for name, ok in res:
        print(('ok   ' if ok else 'FAIL ') + name)
        fail += not ok
    return 1 if fail else 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', default=str(HERE.parents[1]))
    ap.add_argument('--selftest', action='store_true')
    ap.add_argument('--write-legacy', action='store_true')
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    try:
        import subprocess
        c = subprocess.run(['git', '-C', a.root, 'rev-parse', '--path-format=absolute', '--git-common-dir'], capture_output=True, text=True, timeout=20).stdout.strip()
        main_dir = Path(c).parent if c else Path(a.root)
    except Exception:
        main_dir = Path(a.root)
    if a.write_legacy:
        write_legacy(a.root, main_dir)
        return 0
    base = base_legacy_names(a.root)
    if base is None:
        print('WARN  deps_lint: the legacy list\'s baseline is not in git history here: the shrink-only rule is NOT checked')
    bad, stale = lint(a.root, main_dir, base_names=base)
    for b in bad + stale:
        print('FAIL  ' + b)
    if bad or stale:
        return 1
    print(f'PASS: every live check has affects, exact script deps, a deps entry, or is on the legacy list ({len(legacy_names(a.root))} legacy)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
