#!/usr/bin/env python3
"""Lint: every gate lane json declares `affects` (S103 H3, audit 1.3 item 5; 12 s103_* lanes had none, so nothing could select or cache their checks).

  py -I tools\\gate\\affects_lint.py [--root DIR] [--selftest] [--write-legacy]

A lane json passes when it declares "affects" at the top level or on at least one check (builds that run a .ps1 stay without it on purpose: they run
serial and are never cached). Lanes that predate the rule are listed in tools\\gate\\affects_legacy.txt (one lane file name per line, generated by
--write-legacy; the list may only shrink: a lane in it that now declares affects is reported so the line is removed). Any other lane without affects
FAILs, and so does a legacy line naming a lane that no longer exists. Selftest: planted lanes (none / lane-level / check-level / legacy-listed)."""
import argparse
import json
import os
import sys
import tempfile
from pathlib import Path


def declares(data):
    return 'affects' in data or any('affects' in c for c in data.get('checks', []))


def legacy_names(root):
    p = Path(root) / 'tools' / 'gate' / 'affects_legacy.txt'
    if not p.is_file():
        return set()
    return {ln.strip() for ln in p.read_text(encoding='utf-8').splitlines() if ln.strip() and not ln.startswith('#')}


def lint(root):
    lanes = Path(root) / 'tools' / 'gate' / 'lanes'
    legacy = legacy_names(root)
    bad, stale, seen = [], [], set()
    for f in sorted(lanes.glob('*.json')):
        seen.add(f.name)
        try:
            data = json.loads(f.read_text(encoding='utf-8'))
        except Exception as e:
            bad.append(f'{f.name}: unreadable ({e})')
            continue
        ok = declares(data)
        if not ok and f.name not in legacy:
            bad.append(f'{f.name}: no "affects" on the lane or on any check (add the globs of the files its checks read; "cache": false keeps a check uncached)')
        if ok and f.name in legacy:
            stale.append(f'{f.name}: declares affects now; remove it from tools/gate/affects_legacy.txt')
    for n in sorted(legacy - seen):
        stale.append(f'{n}: in affects_legacy.txt but the lane file does not exist')
    return bad, stale


def write_legacy(root):
    lanes = Path(root) / 'tools' / 'gate' / 'lanes'
    names = sorted(f.name for f in lanes.glob('*.json') if not declares(json.loads(f.read_text(encoding='utf-8'))))
    (Path(root) / 'tools' / 'gate' / 'affects_legacy.txt').write_text(
        '# Lanes that predate the "affects" rule (S103 H3). Generated by affects_lint.py --write-legacy; may only shrink. A new lane must declare affects.\n'
        + '\n'.join(names) + '\n', encoding='utf-8')
    print(f'wrote {len(names)} legacy lane names')


def selftest():
    d = Path(tempfile.mkdtemp(prefix='affects_lint_'))
    (d / 'tools' / 'gate' / 'lanes').mkdir(parents=True)
    L = d / 'tools' / 'gate' / 'lanes'
    (L / 'none.json').write_text(json.dumps({'checks': [{'name': 'a', 'cmd': ['x']}]}))
    (L / 'lane.json').write_text(json.dumps({'affects': ['src/**'], 'checks': [{'name': 'a', 'cmd': ['x']}]}))
    (L / 'chk.json').write_text(json.dumps({'checks': [{'name': 'a', 'cmd': ['x'], 'affects': ['src/**']}]}))
    (L / 'old.json').write_text(json.dumps({'checks': [{'name': 'a', 'cmd': ['x']}]}))
    (d / 'tools' / 'gate' / 'affects_legacy.txt').write_text('old.json\nlive_but_fixed.json\n')
    (L / 'live_but_fixed.json').write_text(json.dumps({'affects': ['src/**'], 'checks': []}))
    bad, stale = lint(d)
    res = [('planted lane without affects is caught', [b for b in bad if b.startswith('none.json')]),
           ('lane-level affects passes', not [b for b in bad if b.startswith('lane.json')]),
           ('check-level affects passes', not [b for b in bad if b.startswith('chk.json')]),
           ('a legacy-listed lane passes', not [b for b in bad if b.startswith('old.json')]),
           ('a legacy line whose lane now declares affects is reported stale', [s for s in stale if s.startswith('live_but_fixed.json')]),
           ('exactly one bad lane', len(bad) == 1)]
    fail = 0
    for name, ok in res:
        print(('ok   ' if ok else 'FAIL ') + name)
        fail += not ok
    return 1 if fail else 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', default=str(Path(__file__).resolve().parents[2]))
    ap.add_argument('--selftest', action='store_true')
    ap.add_argument('--write-legacy', action='store_true')
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    if a.write_legacy:
        write_legacy(a.root)
        return 0
    bad, stale = lint(a.root)
    for b in bad + stale:
        print('FAIL  ' + b)
    if bad or stale:
        return 1
    n = len(list((Path(a.root) / 'tools' / 'gate' / 'lanes').glob('*.json')))
    print(f'PASS: every one of {n} lane files declares affects or is on the legacy list ({len(legacy_names(a.root))} legacy)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
