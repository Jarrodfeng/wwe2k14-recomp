r"""q rendermd (S110 lanes RENDERMD, RENDERMD2): WRITE docs/RENDERER.md, one document about how the game builds what gets drawn,
generated from the q index. Never edited by hand; NOT the store (read.s2.db is the store and answers lookups a few lines at a time).

    py tools/q/q.py rendermd [--out PATH] [--check]

  --out PATH   where to write (default docs/RENDERER.md)
  --check      write nothing; exit 1 when the file on disk differs from what would be generated now (the date line is ignored)

Three parts, in this order:
  PART 1  How the systems work: per system the explanation a model wrote (`q read system NAME` -> system-writer -> `q read store-system`),
          printed in full, headed by who wrote it and from how many readings; "not written yet" or a STALE line when that is the case.
  PART 2  Fun facts: one-line curiosities from the readers (`fun:`) and the writers (`facts:`), grouped by system, never a low one.
  PART 3  Reference: the bar, the clusters per system, under everything, what we do not read, not known yet, patterns.
The generator itself is deterministic: all model-written text lives in read.s2.db.

Sources (all read-only): read.s2.db (qread / qreadsys), feedseen.s2.db (qfeedseen: which game functions were seen writing our
renderer's read sites), the static feed table (qfeed / qfeedkey), units.s1.db (qunits), qcover, qsheet (CONFLICT lines).

Every line carries the standing of its source as a mark at its end:
  [game]            the game's own name or string        [seen N runs]  observed in N recorded runs (never a complete list)
  [static]          our static tables                     [reader: high|medium|low]  a reader's reading of a fact sheet: a LEAD, not a fact
  [writer: high|medium]   a system-writer's curiosity, resting on one reader's reading
Rule 1: our words, addresses, names and offsets only: no game code, no listing text.
"""
