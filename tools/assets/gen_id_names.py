"""Session 98: writes src\\assets\\id_names.h (arena and character names by id) from our id tables
db\\ids\\arenas.json and db\\ids\\characters.json (+ dlc_characters.json). Our annotations only (names + ids).
Usage: py -I tools\\assets\\gen_id_names.py   (rerun after editing the tables)"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parents[2]
ids = root / 'db' / 'ids'


def entries(name):
    p = ids / name
    if not p.exists():
        return []
    return json.loads(p.read_text(encoding='utf-8')).get('entries', [])


def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


arenas = sorted({e['id']: e['name'] for e in entries('arenas.json') if e.get('name')}.items())
chars = {}
for f in ('characters.json', 'dlc_characters.json'):
    for e in entries(f):
        if e.get('name') and isinstance(e.get('id'), int):
            chars.setdefault(e['id'], e['name'])
chars = sorted(chars.items())

out = ['// Generated by tools\\assets\\gen_id_names.py from db\\ids\\arenas.json + characters.json (+ dlc_characters.json).',
       '// Do not edit by hand: edit the tables and rerun. Plain C++17 (the phone build uses it too).',
       '#pragma once', '#include <string>', '', 'namespace assets {', '',
       'struct IdName { int id; const char* name; };', '']
out.append('inline constexpr IdName kArenaNames[] = {')
out += [f'    {{{i}, "{esc(n)}"}},' for i, n in arenas]
out.append('};')
out.append('inline constexpr IdName kCharacterNames[] = {')
out += [f'    {{{i}, "{esc(n)}"}},' for i, n in chars]
out.append('};')
# Session 99: the ring announcer per arena (arenas.json "announcer"; its evidence / confidence stay in the table)
ann = sorted((e['id'], e['announcer']) for e in entries('arenas.json') if isinstance(e.get('announcer'), int))
out.append('struct IdId { int id; int value; };')
out.append('// arena -> its ring announcer character where db\\ids\\arenas.json names one (see "announcer_evidence"; else Justin Roberts 187)')
out.append('inline constexpr IdId kArenaAnnouncer[] = {')
out += [f'    {{{i}, {v}}},' for i, v in ann] or ['    {-1, 0},']
out.append('};')
out += ['',
        '// The name for an id, or "" when the table has none.',
        'template <size_t N>',
        'inline const char* IdNameOf(const IdName (&t)[N], int id) {',
        '  for (const IdName& e : t)',
        '    if (e.id == id) return e.name;',
        '  return "";',
        '}',
        'inline const char* ArenaName(int id) { return IdNameOf(kArenaNames, id); }',
        'inline const char* CharacterName(int id) { return IdNameOf(kCharacterNames, id); }',
        '// The arena\'s ring announcer from kArenaAnnouncer, or `dflt`.',
        'inline int ArenaAnnouncerId(int arena, int dflt) {',
        '  for (const IdId& e : kArenaAnnouncer)',
        '    if (e.id == arena) return e.value;',
        '  return dflt;',
        '}',
        '// "No Way Out" or "Arena 5" when unnamed.',
        'inline std::string ArenaLabel(int id) { const char* n = ArenaName(id); return *n ? std::string(n) : "Arena " + std::to_string(id); }',
        'inline std::string CharacterLabel(int id) { const char* n = CharacterName(id); return *n ? std::string(n) : "Wrestler " + std::to_string(id); }',
        '', '}  // namespace assets', '']
dst = root / 'src' / 'assets' / 'id_names.h'
dst.write_text('\n'.join(out), encoding='utf-8')
print(f'{dst}: {len(arenas)} arenas, {len(chars)} characters')
