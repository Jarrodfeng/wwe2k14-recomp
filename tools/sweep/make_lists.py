"""Session 10 (M5 sweep): run lists for tools\\sweep\\run_sweep.ps1, and the full-match scripts.

  py tools\\sweep\\make_lists.py            write out\\harness\\sweep\\lists\\{arenas,roster,full}.json and
                                          tools\\sweep\\scripts\\full_<name>.txt (generated; edit them here)

Lists (one entry per game run; `extra` = that run's flags, given to run_list.ps1 as -ScriptExtras):
  arenas  A1: every match arena (ids 0-9, 11-17, 21-23, 28-56 = 49, names from db\\ids\\arenas.json) on the
          lesnar_bryan scenario: --wwe2k14_launch_arena=N. Script scripts\\arena_check.txt.
  roster  A2: every character archive in the dump (game_data\\extracted\\pac\\ch\\chNNN.pac) except the known
          non-wrestlers (150, 153 commentators; 187, 252 ring announcers; 255 referee; 354, 355 valets), in slot 0 of
          lesnar_bryan against Daniel Bryan (324; Brock Lesnar 343 for 324 himself): slot 0 enters first.
          Script scripts\\roster_check.txt.
  full    A3: Jarrod's five scenarios as full matches, every participant CPU (participant overrides without a pad
          where he controlled someone), with peeks on the sequence id, the judge pointer and mode, the finish type
          G+472 and the winner / loser bytes, and the flight recorder (hang dumps). Script scripts\\full_<name>.txt.

The id lists come from the dump's file names and our id tables only (nothing from the game is written here).
"""
from __future__ import annotations

import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "out" / "harness" / "sweep" / "lists"
SCRIPTS = Path(__file__).resolve().parent / "scripts"
CH_DIR = REPO / "game_data" / "extracted" / "pac" / "ch"

ARENA_IDS = list(range(0, 10)) + list(range(11, 18)) + [21, 22, 23] + list(range(28, 57))
NON_WRESTLERS = {150: "commentator (Michael Cole)", 153: "commentator (Jerry Lawler)",
                 187: "ring announcer (Justin Roberts)", 252: "ring announcer (Howard Finkel)",
                 255: "referee", 354: "valet (Naomi)", 355: "valet (Cameron)"}
BASE = "lesnar_bryan"
OPPONENT, OPPONENT_FOR_OPPONENT = 324, 343

# Guest values peeked during full matches (tools\input_scripts\states.toml, db\match_state.json):
#   seq     sequence id (3 title, 75 menus, 9 in-game)          states.toml seq (high, live)
#   judge   referee judge object pointer                        db g_judge 0x83767B6C (high)
#   jmode   referee mode judge+72 (0 watch, 1 pin count, ...)   db g_judge fields (high)
#   fin     finish type G+472 (0 = undecided)                   db g_match_finish_type 0x8376ACCC (medium)
#   winlose winner / loser bytes G+14584/5 (+ 2 bytes after)    db g_match_winner_loser 0x8376E3EC (medium)
#   scene   scene / phase word                                  states.toml scene_word
PEEKS = ("seq=0x839400F8>0>48,judge=0x83767B6C,jmode=0x83767B6C>72,fin=0x8376ACCC,winlose=0x8376E3EC,"
         "scene=0x836F3940")
FULL_FLAGS = f"--wwe2k14_peek={PEEKS} --wwe2k14_flight_recorder=true"

# name, scenario, participant override (None = the capture's own), pace, cap in minutes of match time after the
# match scene (frames at 60 per second), what it is.
FULL = [
    ("bryan_lesnar_mitb", "bryan_lesnar_mitb", None, "Quick", 40,
     "Daniel Bryan vs Brock Lesnar, Money in the Bank, both CPU in the capture"),
    ("hiac_cena_brodus", "hiac_cena_brodus", "139,319", "Normal", 45,
     "Hell in a Cell, John Cena vs Brodus Clay, both CPU"),
    ("tag_hellno_shield", "tag_hellno_shield", "107,369,324,368", "Normal", 45,
     "Tag: Kane + Daniel Bryan vs Seth Rollins + Roman Reigns, SmackDown, all CPU"),
    ("chamber_6man", "chamber_6man", "139,103,131,279,100,366", "Normal", 60,
     "Elimination Chamber, 6 men, all CPU"),
    ("rumble_40", "rumble_40", None, "Epic", 150,
     "40-man Royal Rumble, the captured entry order, all CPU in the capture's match description"),
]

BOOT = """wait_file SaveData.Dat 3600
wait_frames 160
set 0x0010 0 0 0 0 -1636 -1137
wait_frames 10
set 0x0000 0 0 0 0 -1069 -1234
wait_frames 66
set 0x1000 0 0 0 0 -770 -1136
wait_frames 10
set 0x0000 0 0 0 0 -770 -1136
wait_file MNUIHD.PAC 3600"""


def arena_names() -> dict[int, str]:
    data = json.loads((REPO / "db" / "ids" / "arenas.json").read_text(encoding="utf-8"))
    return {int(e["id"]): str(e.get("name", "")) for e in data.get("entries", [])}


def character_ids() -> list[int]:
    ids = []
    for p in sorted(CH_DIR.glob("*.pac")):
        m = re.fullmatch(r"ch(\d+)\.pac", p.name, re.IGNORECASE)
        if m:
            ids.append(int(m.group(1)))
    return sorted(ids)


def full_script(name: str, desc: str, cap_min: int) -> str:
    cap = cap_min * 60 * 60
    return f"""# Session 10 A3 (M5 sweep): full match '{name}', all CPU. GENERATED by tools\\sweep\\make_lists.py (edit there).
# {desc}.
# Boots to the main menu (title presses of Jarrod's recording 056), lets --wwe2k14_launch fire, takes a screenshot
# every 18000 frames (~5 min) in the background, waits for the match scene (M3.PAC), then for the match to be
# decided: finish type G+472 (0x8376ACCC) != 0 (db\\match_state.json g_match_finish_type, medium confidence; this
# run checks it), at most {cap_min} min of frames. Then screenshots 30 s, 60 s and 70 s later and quit (the post-match
# menu EXIT / REMATCH / MATCH HIGHLIGHTS waits for a button: run 500). on_fail quit. Screenshots f_* are local only.
on_fail quit
log full: start ({name})
{BOOT}
log full: main menu reached (the launcher fires after its idle frames)
wait_file INGAMELUA.PAC 1800
log full: in-game sequence loading
screenshot_every 18000 f
wait_file M3.PAC 36000 optional
log full: match scene wait over
log_state seq
wait_frames 600
screenshot f_m600
wait_state 0x8376ACCC !=0 {cap} 2 optional
log full: decided wait over (finish type G+472)
log_state 0x8376ACCC
log_state 0x8376E3EC
log_state 0x836F3928
screenshot f_decided
wait_frames 1800
screenshot f_dec30
wait_frames 1800
screenshot f_dec60
wait_frames 600
log_state seq
screenshot f_after
wait_frames 60
log full: end
quit
"""


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    names = arena_names()
    arenas = [{"name": f"arena_{a:02d}", "script": str(SCRIPTS / "arena_check.txt"),
               "extra": f"--wwe2k14_launch={BASE} --wwe2k14_launch_arena={a}",
               "meta": {"arena": a, "arena_name": names.get(a, ""), "bg": f"BG{a:02d}.PAC"}}
              for a in ARENA_IDS]
    chars = character_ids()
    roster = []
    for c in chars:
        if c in NON_WRESTLERS:
            continue
        opp = OPPONENT_FOR_OPPONENT if c == OPPONENT else OPPONENT
        roster.append({"name": f"ch_{c}", "script": str(SCRIPTS / "roster_check.txt"),
                       "extra": f"--wwe2k14_launch={BASE} --wwe2k14_launch_participants={c},{opp}",
                       "meta": {"id": c, "opponent": opp, "ch": f"CH{c}.PAC"}})
    full = []
    for name, scen, parts, pace, cap, desc in FULL:
        script = SCRIPTS / f"full_{name}.txt"
        script.write_text(full_script(name, desc, cap), encoding="utf-8", newline="\n")
        extra = f"--wwe2k14_launch={scen}"
        if parts:
            extra += f" --wwe2k14_launch_participants={parts}"
        full.append({"name": name, "script": str(script), "extra": f"{extra} {FULL_FLAGS}",
                     "meta": {"scenario": scen, "participants": parts, "pace": pace, "cap_min": cap,
                              "desc": desc}})
    for list_name, items in (("arenas", arenas), ("roster", roster), ("full", full)):
        (OUT / f"{list_name}.json").write_text(json.dumps({"list": list_name, "items": items}, indent=1),
                                               encoding="utf-8")
        print(f"{list_name}: {len(items)} runs -> {OUT / (list_name + '.json')}")
    skipped = [c for c in chars if c in NON_WRESTLERS]
    print(f"character archives: {len(chars)}; skipped non-wrestlers: {skipped}")


if __name__ == "__main__":
    main()
