"""Frozen-frame check route (Session 66, F1): same-frame pictures of hot renderer flags with no replay noise.

The scene freeze (`cvar wwe2k14_freeze true`, src\\scene_freeze.h) keeps the renderer drawing the held scene every
frame. In each scene the route freezes, shoots the base twice (an A/A pair: is the held frame stable?), then for each
flag set: sets it, shoots, puts the base values back, shoots the base again. Compare with
`py tools\\s66\\shot_diff.py RUN fz_<scene>_base1 fz_<scene>_<k> ...` (identical = exact for that frame).
Launched Lesnar vs Bryan (--wwe2k14_launch=lesnar_bryan --wwe2k14_preset_low=true), scenes Brock's entrance (343.bik2 +
200), Bryan's (324.bik2 + 300), the match (M3.PAC + 600).

    py tools\\s66\\freeze_route.py NAME "cvar=on_value/off_value[;cvar=...]" ["..." ...]   -> short\\s66_fz_NAME.txt
Each quoted argument is one flag set (several cvars switched together), k = 1, 2, ... in the shot names.
"""
import os
import sys

R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SHORT = os.path.join(R, 'tools', 'input_scripts', 'short')
SCENES = (('brock', '343.bik2', 1800, 200), ('bryan', '324.bik2', 20000, 300), ('match', 'M3.PAC', 30000, 600))


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    name, sets = sys.argv[1], []
    for arg in sys.argv[2:]:
        pairs = []
        for item in arg.split(';'):
            cvar, values = item.split('=', 1)
            on, off = values.split('/', 1)
            pairs.append((cvar.strip(), on.strip(), off.strip()))
        sets.append(pairs)
    src = open(os.path.join(SHORT, 'profile_lesnar_bryan.txt'), encoding='utf-8').read().splitlines()
    nav = src[src.index('wait_file SaveData.Dat 3600'):src.index('wait_file 343.bik2 1800')]
    out = [f'# harness: fast-forward ok (Session 66 F1 frozen-frame check {name}: generated by tools\\s66\\freeze_route.py)',
           '# Flag sets: ' + ' | '.join(';'.join(f'{c}={a}/{b}' for c, a, b in s) for s in sets),
           '# Use with --wwe2k14_launch=lesnar_bryan --wwe2k14_preset_low=true. on_fail quit. Shots fz_* are local only.',
           'on_fail quit', f'log bench: start s66_fz_{name} (launch)'] + nav
    for scene, marker, timeout, offset in SCENES:
        out += [f'wait_file {marker} {timeout}', f'log scene={scene}', f'wait_frames {offset}',
                'cvar wwe2k14_freeze true', 'wait_frames 30', f'screenshot fz_{scene}_base1', 'wait_frames 1',
                f'screenshot fz_{scene}_base2']
        for k, pairs in enumerate(sets, 1):
            out += [f'cvar {c} {on}' for c, on, _ in pairs] + ['wait_frames 8', f'screenshot fz_{scene}_{k}']
            out += [f'cvar {c} {off}' for c, _, off in pairs] + ['wait_frames 8', f'screenshot fz_{scene}_base{k + 2}']
        out += ['cvar wwe2k14_freeze false']
    out += ['log bench: done', 'quit']
    path = os.path.join(SHORT, f's66_fz_{name}.txt')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print(path)


if __name__ == '__main__':
    main()
