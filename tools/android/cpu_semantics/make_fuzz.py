"""Session 73: turn the SDK's generated PPC instruction tests (ppc_test_cases.cpp) into a differential fuzz: each test's
instruction sequence (the same recompiled function) is run ROUNDS times with every input register replaced by a random
value (biased towards edge cases), and every register the test checks is printed as bits. The same file is built for
x86-64 and ARM64 (run_fuzz.ps1) and the outputs diffed: any difference is an ARM / x86 divergence of the recompiled
code. Memory set-up lines stay; trap tests (tw / td) keep their fixed inputs (random ones trap by design).

    py -I make_fuzz.py <generated dir> <out .cpp> [rounds]
"""
import re
import sys

gen_dir, out_path = sys.argv[1], sys.argv[2]
rounds = int(sys.argv[3]) if len(sys.argv) > 3 else 100
src = open(gen_dir + '/ppc_test_cases.cpp', encoding='utf-8').read()

blocks = re.findall(r'TEST_CASE\("([^"]+)",[^)]*\)\s*\{(.*?)\n\}\n', src, re.S)
assign = re.compile(r'^\s*(ctx\.(?:r|f|v)\d+\.(?:u64|f64|u32\[\d\]))\s*=\s*([^;]+);\s*$')
call = re.compile(r'^\s*(\w+)\(ctx, memory\);\s*$')
require = re.compile(r'REQUIRE\((ctx\.[\w\[\]\.]+)\s*==')

out = []
out.append('// Generated by tools\\android\\cpu_semantics\\make_fuzz.py (Session 73). Do not edit.')
out.append('#include "fuzz_support.h"')
out.append('#include "ppc_test_decls.h"')
funcs = []
for i, (name, body) in enumerate(blocks):
    lines = body.split('\n')
    pre, fn, checks = [], None, []
    for line in lines:
        m = call.match(line)
        if m:
            fn = m.group(1)
            continue
        if fn is None:
            if 'get_memory' in line or 'virtual_membase' in line or 'PPCContext ctx' in line or 'loadFromHost' in line:
                continue
            a = assign.match(line)
            trap = name.split('.')[0] in ('tw', 'twi', 'td', 'tdi')
            if a and not trap:
                lhs = a.group(1)
                if '.f64' in lhs:
                    pre.append(f'    {lhs} = fz::RandF64(rng);')
                elif '.u32[' in lhs:
                    pre.append(f'    {lhs} = fz::RandV32(rng);')
                else:
                    pre.append(f'    {lhs} = fz::Rand64(rng, {"true" if lhs.startswith("ctx.f") else "false"});')
            elif line.strip():
                pre.append(line)
        else:
            m = require.search(line)
            if m and m.group(1) not in checks:
                checks.append(m.group(1))
    if fn is None:
        continue
    fid = f'fz_{i}'
    funcs.append((fid, name))
    out.append(f'static void {fid}(uint8_t* memory, fz::Rng& rng, FILE* f) {{')
    out.append(f'  for (int round = 0; round < {rounds}; ++round) {{')
    out.append('    PPCContext ctx{};')
    out.append('    ctx.fpscr.loadFromHost();')
    out.extend(pre)
    out.append(f'    {fn}(ctx, memory);')
    out.append(f'    std::fprintf(f, "{name} %d", round);')
    for c in checks:
        out.append(f'    fz::Print(f, {c});')
    out.append('    std::fputc(\'\\n\', f);')
    out.append('  }')
    out.append('}')
out.append('const fz::Case fz::kCases[] = {')
for fid, name in funcs:
    out.append(f'  {{"{name}", {fid}}},')
out.append('};')
out.append(f'const int fz::kCaseCount = {len(funcs)};')
open(out_path, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(f'{len(funcs)} cases x {rounds} rounds -> {out_path}')
