"""cvar_shard (S110 CVARSHARD, step 1 of the main.cpp split; docs\\research\\s110\\MAINSPLIT.md "Step 1"): no header of src\\ holds a REXCVAR_DEFINE_*.

A header declares its cvar (`REXCVAR_DECLARE(type, name);`, the project's pattern for a cvar defined elsewhere) under the same namespace and the same `#if`; the definition lives in
one of SHARDS generated units src\\cvars\\cvars_<n>.cpp, which are direct sources of the game target (CMakeLists.txt), so main.cpp no longer instantiates the cvar machinery.

  py -I tools\\compile\\cvar_shard.py             apply: rewrite every header definition to its declare, regenerate the shards (idempotent; run it after a merge)
  py -I tools\\compile\\cvar_shard.py --check     exit 1 when a header holds a definition (a new cvar: run the tool without --check) or a shard is out of date
  py -I tools\\compile\\cvar_shard.py --list      the sites found in the headers and what would be skipped (writes nothing)
  py -I tools\\compile\\cvar_shard.py --selftest  planted synthetic headers (a define under #if, a chained define, an un-converted header --check must refuse)

Rules.
  * The shards ARE the database once a header is converted: a rerun reads them back (each group of definitions starts with a `//@ header | namespace | condition` line), adds the
    definitions found in headers, and writes every shard again. Nothing else holds the definitions; do not edit a shard by hand (the check refuses a hand edit).
  * A cvar goes to shard crc32(name) % SHARDS: a new cvar moves no other cvar between shards. Inside a shard: by header path, then the order the definitions had in the header.
  * The condition of a definition = the header's own `#if` stack at the define, AND the conditions under which a unit of the game target includes the header (a walk of the
    `#include "x.h"` lines from the unit list in CMakeLists.txt and the keep_stream lists: `#if !WWE2K14_STREAM()` around an include in wwe2k14_app.h is kept). A header reached by
    several routes gets the OR of the routes. The definition text moves verbatim (chained .range() / .allowed() included).
  * PARKED: a header no unit of the game target includes (written, not wired: src\\nf\\all.h names three) keeps its definition. It compiles nowhere, so it cannot break the
    split, and its include route is unknown until a unit includes it: then --check fails on it and a run moves it under its real condition (S110 CVARSHARD review: before, it
    went to a shard under a stored `#if 0`).
  * SKIPPED (the tool lists them; --check fails until a person converts them): a default that is not a literal (true / false / a number / a string), a define under a macro,
    in a class / function / anonymous namespace, a COMMAND cvar. src\\cvars\\cvars_hand.cpp holds the ones done by hand (never touched by this tool).
"""
