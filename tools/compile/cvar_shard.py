        msgs = []
        ok('split part: --check fails and names the definition at its real place (the part, line 2)', run(base, check=True, say=msgs.append) == 1
           and any('src/split_p/part.inc:2' in m and 'wwe2k14_split_part' in m for m in msgs), '; '.join(msgs))
        parent_before = get('src/split_p.h')
        run(base, say=lambda *a: None)
        ok('split part: apply declares it IN the part; the parent keeps its include line (the split stays)', 'REXCVAR_DECLARE(bool, wwe2k14_split_part);' in get('src/split_p/part.inc')
           and 'REXCVAR_DEFINE_BOOL' not in get('src/split_p/part.inc') and get('src/split_p.h') == parent_before, get('src/split_p/part.inc') + '|' + get('src/split_p.h'))
