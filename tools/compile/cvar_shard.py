# ------------------------------------------------------------------------------------------------------------------------------ lexing
def blank(text):
    """text with comments and the insides of string / char literals replaced by spaces (newlines and offsets kept; the quotes stay)."""
    out = list(text)
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == '/' and text[i + 1:i + 2] == '/':
            j = i
            while j < n and text[j] != '\n':
                # a comment ending in a backslash continues (rare; keep it simple: only a trailing backslash before \n or \r\n)
                j += 1
            for k in range(i, j):
                if out[k] not in '\r\n':
                    out[k] = ' '
            i = j
        elif c == '/' and text[i + 1:i + 2] == '*':
            j = text.find('*/', i + 2)
            j = n if j < 0 else j + 2
            for k in range(i, j):
                if out[k] not in '\r\n':
                    out[k] = ' '
            i = j
        elif c == 'R' and text[i + 1:i + 2] == '"' and not (i and (text[i - 1].isalnum() or text[i - 1] == '_')):
            m = re.compile(r'R"([^()\\ ]{0,16})\(').match(text, i)
            if m:
                end = text.find(')' + m.group(1) + '"', m.end())
                end = n if end < 0 else end + len(m.group(1)) + 2
                for k in range(m.end(), max(m.end(), end - 1 - len(m.group(1)))):
                    if out[k] not in '\r\n':
                        out[k] = ' '
                i = end
            else:
                i += 1
        elif c == '"' or (c == "'" and not (i and text[i - 1].isalnum())):
            j = i + 1
            while j < n and text[j] != c and text[j] != '\n':
                j += 2 if text[j] == '\\' else 1
            for k in range(i + 1, min(j, n)):
                if out[k] not in '\r\n':
                    out[k] = ' '
            i = j + 1
        else:
            i += 1
    return ''.join(out)


def match_paren(code, i):
    """index just after the ')' matching the '(' at code[i] (code = blanked text), or -1."""
    depth = 0
    n = len(code)
    while i < n:
        c = code[i]
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return -1


def split_args(code, text, a, b):
    """the top-level comma separated pieces of text[a:b] (parenthesis / brace / bracket aware via the blanked code)."""
    out, depth, start = [], 0, a
    for i in range(a, b):
        c = code[i]
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
        elif c == ',' and depth == 0:
            out.append(text[start:i].strip())
            start = i + 1
    out.append(text[start:b].strip())
    return out


# ------------------------------------------------------------------------------------------------------------------------------ one text
class Site:
    def __init__(self, **kw):
        self.__dict__.update(kw)


def directives(text, code):
    """[(line start offset, line end offset, directive text)] of the preprocessor lines (continuations joined), from the blanked code."""
    out = []
    pos, n = 0, len(code)
    while pos < n:
        e = code.find('\n', pos)
        e = n if e < 0 else e
        line = code[pos:e]
        if line.lstrip().startswith('#'):
            s0, text_parts = pos, [line.rstrip('\r')]
            while text_parts[-1].endswith('\\') and e < n:
                nxt = code.find('\n', e + 1)
                nxt = n if nxt < 0 else nxt
                text_parts[-1] = text_parts[-1][:-1]
                text_parts.append(code[e + 1:nxt].rstrip('\r'))
                e = nxt
            out.append((s0, e, ' '.join(p.strip() for p in text_parts).lstrip('#').strip()))
        pos = e + 1
    return out


DEFAULT_NAMES = set()   # the names src\cvars\cvar_defaults.h declares: a non-literal default made of these only is moved with its text (Tree sets it)


def scan_text(text):
    """-> (includes [(target, conds)], sites [Site]) of one header text. conds = the #if stack as strings, include guards left out."""
    code = blank(text)
    dirs = directives(text, code)
    masked = list(code)
    for s0, e, _d in dirs:
        for k in range(s0, e):
            if masked[k] not in '\r\n':
                masked[k] = ' '
    masked = ''.join(masked)
    # the #if stack at each offset: replay the directives in order, record (offset -> conds) lazily through a sorted list of changes
    changes = []   # (offset after the directive, conds tuple)
    stack = []     # each: [list of cond strings of the chain so far, current cond or None (guard)]
    includes = []
    macro_defs = []   # offsets of REXCVAR_DEFINE_ inside a directive
    for idx, (s0, e, d) in enumerate(dirs):
        m = re.match(r'(\w+)\s*(.*)$', d, re.S)
        if not m:
            changes.append((e, tuple(c for c in (x[1] for x in stack) if c)))
            continue
        kw, rest = m.group(1), m.group(2).strip()
        if kw in ('if', 'ifdef', 'ifndef'):
            cond = rest if kw == 'if' else ('defined(%s)' % rest if kw == 'ifdef' else '!defined(%s)' % rest)
            if kw == 'ifndef' and idx + 1 < len(dirs) and re.match(r'define\s+%s\b' % re.escape(rest), dirs[idx + 1][2]) and not stack:
                stack.append([[cond], None])   # the include guard: never a condition
            else:
                stack.append([[cond], cond])
        elif kw in ('elif', 'else') and stack:
            prev = stack[-1][0]
            cond = ' && '.join(['!(%s)' % p for p in prev] + (['(%s)' % rest] if kw == 'elif' else []))
            if kw == 'elif':
                prev.append(rest)
            if stack[-1][1] is not None:   # (a guard stays a guard)
                stack[-1][1] = cond
        elif kw == 'endif' and stack:
            stack.pop()
        elif kw == 'include':
            im = re.search(r'#\s*include\s*"([^"\n]+)"', text[s0:e])   # (the blanked text has no string contents)
            if im:
                includes.append((im.group(1), tuple(c for c in (x[1] for x in stack) if c)))
        if 'REXCVAR_DEFINE_' in d:
            macro_defs.append(s0)
        changes.append((e, tuple(c for c in (x[1] for x in stack) if c)))
    import bisect
    ch_off = [c[0] for c in changes]

    def conds_at(off):
        i = bisect.bisect_left(ch_off, off) - 1
        return changes[i][1] if i >= 0 else ()
    dir_lines = sorted((text.count('\n', 0, s0), text.count('\n', 0, e)) for s0, e, _d in dirs)
    # brace stack: namespace names / other
    sites = []
    stack_b = []
    last_end = 0
    pos, n = 0, len(masked)
    define = re.compile(r'\bREXCVAR_DEFINE_(\w+)')
    nxt = define.search(masked, 0)
    brace = re.compile(r'[{}]')
    while True:
        b = brace.search(masked, pos)
        if nxt is not None and (b is None or nxt.start() < b.start()):
            m = nxt
            site = analyse(text, masked, m, stack_b, conds_at(m.start()), dir_lines)
            sites.append(site)
            pos = max(site.end, m.end()) if site.end > 0 else m.end()
            last_end = pos
            nxt = define.search(masked, pos)
            continue
        if b is None:
            break
        if masked[b.start()] == '{':
            seg = masked[last_end:b.start()]
            seg = re.split(r'[;{}]', seg)[-1].strip()
            nm = re.match(r'(?:inline\s+)?namespace\s*([\w:\s]*)$', seg)
            stack_b.append(('ns', re.sub(r'\s+', '', nm.group(1))) if nm else ('other', seg[:30]))
        else:
            if stack_b:
                stack_b.pop()
        pos = b.end()
        last_end = pos
        while nxt is not None and nxt.start() < pos:
            nxt = define.search(masked, pos)
    for off in macro_defs:
        sites.append(Site(kind='?', name='?', start=off, end=off, line=text.count('\n', 0, off) + 1, skip='under a macro / directive line', ns=(), conds=(), text='', default=''))
    sites.sort(key=lambda s: s.start)
    return includes, sites


def analyse(text, masked, m, stack_b, conds, dir_lines):
    kind = m.group(1)
    line = text.count('\n', 0, m.start()) + 1
    base = dict(kind=kind, start=m.start(), end=-1, line=line, ns=(), conds=conds, name='?', default='', text='', skip=None)
    if any(k != 'ns' for k, _v in stack_b) or any(k == 'ns' and v == '' for k, v in stack_b):
        base['skip'] = 'inside a %s' % ('class / function / extern block (%s)' % [v for k, v in stack_b if k != 'ns'][:1] if any(k != 'ns' for k, _v in stack_b) else 'anonymous namespace')
    base['ns'] = tuple(p for k, v in stack_b if k == 'ns' for p in v.split('::'))
    i = m.end()
    while i < len(masked) and masked[i] in ' \t\r\n':
        i += 1
    if i >= len(masked) or masked[i] != '(':
        base['skip'] = base['skip'] or 'no argument list'
        return Site(**base)
    j = match_paren(masked, i)
    if j < 0:
        base['skip'] = base['skip'] or 'unbalanced'
        return Site(**base)
    args = split_args(masked, text, i + 1, j - 1)
    while True:   # chained .range(...) / .allowed(...) ...
        k = j
        while k < len(masked) and masked[k] in ' \t\r\n':
            k += 1
        if k < len(masked) and masked[k] == '.':
            mm = re.compile(r'\.\s*\w+\s*\(').match(masked, k)
            if not mm:
                break
            j2 = match_paren(masked, mm.end() - 1)
            if j2 < 0:
                break
            j = j2
        else:
            break
    k = j
    while k < len(masked) and masked[k] in ' \t\r\n':
        k += 1
    if k >= len(masked) or masked[k] != ';':
        base['skip'] = base['skip'] or 'no terminating ;'
        return Site(**base)
    base['end'] = k + 1
    base['text'] = text[m.start():k + 1]
    first, last = text.count('\n', 0, m.start()), text.count('\n', 0, k)
    if any(first < a_ <= last or first < b_ <= last for a_, b_ in dir_lines):
        base['skip'] = base['skip'] or 'a preprocessor line inside the definition'
    if kind not in TYPES:
        base['skip'] = base['skip'] or 'cvar kind %s (COMMAND or unknown)' % kind
    if len(args) != 4:
        base['skip'] = base['skip'] or '%d arguments' % len(args)
        return Site(**base)
    base['name'], base['default'] = args[0], args[1]
    if not re.match(r'^[A-Za-z_]\w*$', args[0]):
        base['skip'] = base['skip'] or 'name is not an identifier'
    elif not LITERAL.match(args[1]) and not set(re.findall(r'[A-Za-z_]\w*', blank(args[1]))) <= (DEFAULT_NAMES | {'true', 'false'}):
        base['skip'] = base['skip'] or 'default is not a literal: %s' % re.sub(r'\s+', ' ', args[1])[:50]
    return Site(**base)


# ------------------------------------------------------------------------------------------------------------------------------ the tree
class Tree:
    def __init__(self, root):
        self.root = os.path.abspath(root)
        self.cache = {}
        self.ucache = {}
        DEFAULT_NAMES.clear()
        d = self.rd(SHARD_DIR + '/cvar_defaults.h') or ''
        DEFAULT_NAMES.update(re.findall(r'^\s*#\s*define\s+(\w+)', d, re.M))
        DEFAULT_NAMES.update(re.findall(r'\bconstexpr\s+[\w:]+\s+(\w+)\s*=', d))

    def rd(self, rel):
        try:
            with open(os.path.join(self.root, rel), encoding='utf-8', errors='surrogateescape', newline='') as f:
                return f.read()
        except OSError:
            return None

    def rd_unit(self, rel, _depth=0):
        """(text, segs): `rel` as rd() reads it with its split parts expanded in place (S111 SPLIT-WIRE review: a part such as
        src/renderer_adapter/reader/draw.inc is a run of its parent header, inside the parent's namespace and #if; alone it is neither a
        header nor in any scope). segs = [(start, end, file rel, offset in that file)] of each run of the text. (None, []) when unreadable."""
        if rel in self.ucache:
            return self.ucache[rel]
        t = self.rd(rel)
        if t is None:
            return None, []
        if 'split:' not in t or _depth > 8:
            res = (t, [(0, len(t), rel, 0)])
        else:
            out, segs, pos, off, run0 = [], [], 0, 0, 0

            def close(end):
                nonlocal pos
                if end > run0:
                    segs.append((pos, pos + end - run0, rel, run0))
                    out.append(t[run0:end])
                    pos += end - run0
            for ln in t.splitlines(keepends=True):
                m = SPLIT_INC.match(ln)
                pt = None
                if m:
                    prel = os.path.normpath(os.path.join(os.path.dirname(rel), m.group(1))).replace('\\', '/')
                    pt, psegs = self.rd_unit(prel, _depth + 1)
                if pt is None:
                    off += len(ln)
                    continue
                close(off)
                segs.extend((pos + s, pos + e, f, fs) for s, e, f, fs in psegs)
                out.append(pt)
                pos += len(pt)
                off += len(ln)
                run0 = off
            close(off)
            res = (''.join(out), segs)
        self.ucache[rel] = res
        return res

    def where(self, rel, off):
        """'file:line' of offset `off` of rel's expanded text: the part file and its own line when the offset is in a part"""
        text, segs = self.rd_unit(rel)
        for s, e, f, fs in segs:
            if s <= off < e:
                return '%s:%d' % (f, (self.rd(f) or '').count('\n', 0, fs + off - s) + 1)
        return '%s:%d' % (rel, (text or '').count('\n', 0, off) + 1)

    def headers(self):
        out = []
        for dp, dn, fn in os.walk(os.path.join(self.root, 'src')):
            dn.sort()
            for f in sorted(fn):
                if f.endswith(('.h', '.hpp')):
                    out.append(os.path.relpath(os.path.join(dp, f), self.root).replace('\\', '/'))
        return out

    def scan(self, rel):
        if rel not in self.cache:
            t = self.rd_unit(rel)[0]   # a split parent is scanned whole: its parts' definitions with the parent's namespace and #if
            self.cache[rel] = scan_text(t) if t is not None else ([], [])
        return self.cache[rel]

    def resolve(self, includer, target):
        d = os.path.dirname(includer)
        for cand in (os.path.normpath(os.path.join(d, target)), os.path.normpath(os.path.join('src', target))):
            cand = cand.replace('\\', '/')
            if os.path.isfile(os.path.join(self.root, cand)):
                return cand
        return None

    def unit_roots(self):
        """[(unit, implied conds)]: the game target's units (CMakeLists.txt + the keep_stream lists)."""
        sys.path.insert(0, os.path.join(HERE, '..', 'handback'))
        import cvar_pp
        cm = cvar_pp.cmake_sources(self.rd('CMakeLists.txt') or '')

        def lst(rel):
            return {x.strip() for x in (self.rd(rel) or '').splitlines() if x.strip().startswith('src/')}
        on_only, off_only = lst('tools/scene/keep_stream_sources.txt'), lst('tools/scene/keep_stream_off_sources.txt')
        roots = []
        for u in sorted(cm | off_only):
            if not os.path.isfile(os.path.join(self.root, u)):
                continue
            imp = ('WWE2K14_STREAM()',) if u in on_only else ('!WWE2K14_STREAM()',) if u in off_only else ()
            roots.append((u, imp))
        return roots

    def reach(self):
        """{header: set of condition tuples under which some unit of the game target includes it}."""
        seen = {}
        work = list(self.unit_roots())
        done = set()
        while work:
            rel, conds = work.pop()
            if (rel, conds) in done:
                continue
            done.add((rel, conds))
            seen.setdefault(rel, set()).add(conds)
            for target, c in self.scan(rel)[0]:
                r = self.resolve(rel, target)
                if r:
                    # a condition already on the route adds nothing (a route is an AND): so an include cycle repeats a (header, route) and ends (S111 CACTHUMB:
                    # `#if !defined(X)` around an include back into the includer grew the route by one term per lap until MemoryError). First-seen order is kept,
                    # which is the order cond_expr's own de-duplication kept, so no shard text changes.
                    nc = conds
                    for x in c:
                        if x not in nc:
                            nc += (x,)
                    work.append((r, nc))
        return seen


# ------------------------------------------------------------------------------------------------------------------------------ conditions
SIMPLE = re.compile(r'^(?:!?\w+(?:\(\))?|!?defined\(\w+\)|!?defined\s+\w+)$')


def norm_cond(c):
    """one condition string made canonical: no outer parentheses, `!(X)` of a simple X as `!X`."""
    c = c.strip()
    while c.startswith('(') and c.endswith(')') and match_paren(c, 0) == len(c):
        c = c[1:-1].strip()
    m = re.match(r'^!\s*\((.*)\)$', c)
    if m and SIMPLE.match(m.group(1).strip()) and match_paren(c, c.index('(')) == len(c):
        inner = m.group(1).strip()
        c = inner[1:].strip() if inner.startswith('!') else '!' + inner
    return c


def term(c):
    return c if SIMPLE.match(c) else '(%s)' % c


def cond_expr(paths, own):
    """one #if expression ('' = unconditional) for the OR of the include routes `paths` (tuples) each ANDed with the header's own conditions `own`."""
    terms = []
    for p in sorted(paths):
        items = []
        for c in tuple(p) + tuple(own):
            c = norm_cond(c)
            if c not in items:
                items.append(c)
        terms.append(tuple(items))
    terms = sorted(set(terms), key=lambda t: (len(t), t))
    kept = []
    for t in terms:   # absorption: a route whose conditions contain another route's is implied by it
        if not any(set(k) <= set(t) for k in kept):
            kept.append(t)
    if any(not t for t in kept):
        return ''
    singles = {t[0] for t in kept if len(t) == 1}
    if any(('!' + s if not s.startswith('!') else s[1:]) in singles for s in singles):
        return ''   # X || !X
    ands = [' && '.join(term(c) for c in t) for t in kept]
    if len(ands) == 1:
        return ands[0]
    return ' || '.join('(%s)' % a if ' && ' in a or ' || ' in a else a for a in ands)


# ------------------------------------------------------------------------------------------------------------------------------ the shards
def shard_of(name):
    return zlib.crc32(name.encode()) % SHARDS


def shard_path(i):
    return '%s/cvars_%d.cpp' % (SHARD_DIR, i)


class Entry:
    def __init__(self, header, ns, cond, text, name, kind, seq):
        self.header, self.ns, self.cond, self.text, self.name, self.kind, self.seq = header, ns, cond, text, name, kind, seq


