def read_shards(tree):
    """-> [Entry] the definitions the shards hold now (file order of shard 0..SHARDS-1). A shard that does not parse as the tool writes it is reported by the check (its text differs)."""
    out = []
    for i in range(SHARDS):
        t = tree.rd(shard_path(i))
        if t is None:
            continue
        lines = t.replace('\r\n', '\n').split('\n')
        pos = 0
        for ln_i, ln in enumerate(lines):
            m = MARK.match(ln)
            if not m:
                continue
            parts = [p.strip() for p in m.group(1).split(' | ', 2)]
            header, ns, cond = parts[0], parts[1] if len(parts) > 1 else '', parts[2] if len(parts) > 2 else ''
            ns = '' if ns == '-' else ns
            cond = '' if cond == '-' else cond
            body_start = sum(len(x) + 1 for x in lines[:ln_i + 1])
            # the group's body ends at the next marker line or the end of the file
            nxt = next((j for j in range(ln_i + 1, len(lines)) if MARK.match(lines[j])), len(lines))
            body = '\n'.join(lines[ln_i + 1:nxt])
            _inc, sites = scan_text(body)
            for s in sites:
                if s.skip or not s.text:
                    continue
                out.append(Entry(header, tuple(x for x in ns.split('::') if x), cond, s.text, s.name, s.kind, len(out)))
    return out


def render_shard(i, entries):
    parts = [PROLOGUE % (BANNER % (i, SHARDS))]
    prev = None
    open_ns = False
    open_if = False

    def close():
        nonlocal open_ns, open_if
        if open_ns:
            parts.append('}  // namespace')
            open_ns = False
        if open_if:
            parts.append('#endif')
            open_if = False
    for e in entries:
        key = (e.header, e.ns, e.cond)
        if key != prev:
            close()
            parts.append('')
            parts.append('//@ %s | %s | %s' % (e.header, '::'.join(e.ns) or '-', e.cond or '-'))
            if e.cond:
                parts.append('#if %s' % e.cond)
                open_if = True
            if e.ns:
                parts.append('namespace %s {' % '::'.join(e.ns))
                open_ns = True
            prev = key
        parts.append(e.text)
    close()
    return '\n'.join(parts) + '\n'


def build(tree, sites_by_header, reach):
    """-> (entries per shard, header rewrites {header: new text}, skipped [(header, line, name, why)])."""
    existing = read_shards(tree)
    new, skipped = [], []
    parked = set()
    rewrites = {}
    for hdr in sorted(sites_by_header):
        sites = sites_by_header[hdr]
        _text, segs = tree.rd_unit(hdr)   # the sites' offsets are in the expanded text; each edit goes to the file (parent or part) that holds it
        paths = reach.get(hdr)
        edits = {}
        for s in sites:
            seg = next((g for g in segs if g[0] <= s.start and s.end <= g[1]), None) if not s.skip else None
            if s.skip or seg is None:
                skipped.append((hdr, s.line, s.name, s.skip or 'the definition runs across a split part boundary', tree.where(hdr, s.start)))
                continue
            if not paths:
                parked.add((s.name, hdr, s.ns))   # PARKED (the docstring): the definition stays in the header; a shard entry it left there before is dropped
                continue
            new.append(Entry(hdr, s.ns, cond_expr(paths, s.conds), s.text, s.name, s.kind, 0))   # (the shard groups by the header the units include: a part's under its parent)
            edits.setdefault(seg[2], []).append((seg[3] + s.start - seg[0], seg[3] + s.end - seg[0], 'REXCVAR_DECLARE(%s, %s);' % (TYPES[s.kind], s.name)))
        for frel, eds in edits.items():
            ft = tree.rd(frel)
            out, last = [], 0
            for a, b, rep in sorted(eds):
                out.append(ft[last:a])
                out.append(rep)
                last = b
            out.append(ft[last:])
            rewrites[frel] = ''.join(out)
    # existing entries first (their file order), then the new ones in (header, line) order; a stable sort on the header path keeps each header's own order
    # a definition found in a header whose (name, header, namespace) a shard already holds REPLACES it: the header is the newer edit (a merge that brought a lane's changed define back)
    fresh = {(e.name, e.header, e.ns) for e in new} | parked
    allv = [e for e in existing if (e.name, e.header, e.ns) not in fresh] + new
    for k, e in enumerate(allv):
        e.seq = k
    byname = {}
    for e in allv:
        byname.setdefault((e.name, e.header, e.cond), []).append(e)
    per = [[] for _ in range(SHARDS)]
    for e in sorted(allv, key=lambda e: (e.header, e.seq)):
        per[shard_of(e.name)].append(e)
    return per, rewrites, skipped


def write(tree, rel, text, eol='\n'):
    p = os.path.join(tree.root, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, 'w', encoding='utf-8', errors='surrogateescape', newline='') as f:
        f.write(text.replace('\n', eol) if eol != '\n' else text)


def run(root, check=False, list_only=False, say=print):
    """-> exit code. check: write nothing, 1 when a header holds a definition or a shard differs."""
    tree = Tree(root)
    sites_by_header = {}
    total = 0
    for h in tree.headers():
        if h.replace('\\', '/').startswith(SHARD_DIR + '/'):
            continue
        t = tree.rd_unit(h)[0]
        if t is None or 'REXCVAR_DEFINE_' not in t:
            continue
        sites = tree.scan(h)[1]
        if sites:
            sites_by_header[h] = sites
            total += len(sites)
    reach = tree.reach() if sites_by_header else {}
    per, rewrites, skipped = build(tree, sites_by_header, reach)
    parked = {h: s for h, s in sites_by_header.items() if not reach.get(h)}   # (build() left these in their headers)
    sites_by_header = {h: s for h, s in sites_by_header.items() if reach.get(h)}
    skipped = [x for x in skipped if x[0] in sites_by_header]
    total = sum(len(s) for s in sites_by_header.values())
    stale = []
    for i in range(SHARDS):
        want = render_shard(i, per[i])
        have = tree.rd(shard_path(i))
        if have is None or have.replace('\r\n', '\n') != want:
            stale.append((i, want))
    if list_only:
        for h in sorted(sites_by_header):
            for s in sites_by_header[h]:
                say('%s  %s %s  ns=%s  %s%s' % (tree.where(h, s.start), s.kind, s.name, '::'.join(s.ns) or '-', ('SKIP: ' + s.skip) if s.skip else 'ok', ''))
        for h, ln, nm, why, at in skipped:
            if not why.startswith('default is not') and 'inside a' not in why:
                say('SKIPPED %s  %s: %s' % (at, nm, why))
        for h in sorted(sites_by_header):
            for s in sites_by_header[h]:
                if s.conds or reach.get(h) != {()}:
                    say('COND %s %s: %s' % (tree.where(h, s.start), s.name, cond_expr(reach.get(h) or set(), s.conds) or '(none)'))
        for h in sorted(parked):
            for s in parked[h]:
                say('PARKED %s  %s (no unit of the game target includes the header: the definition stays there)' % (tree.where(h, s.start), s.name))
        say('cvar_shard: %d site(s) in %d header(s), %d to move, %d skipped, %d parked' % (total, len(sites_by_header), total - len(skipped), len(skipped),
                                                                                          sum(len(s) for s in parked.values())))
        return 0
    for h, ln, nm, why, at in skipped:
        say('skipped  %s  %s: %s' % (at, nm, why))
    if check:
        for h in sorted(sites_by_header):
            for s in sites_by_header[h]:
                say('%s: %s is DEFINED in a header: run `py -I tools\\compile\\cvar_shard.py` (it moves the definition to a shard and leaves a REXCVAR_DECLARE)%s'
                    % (tree.where(h, s.start), s.name, ' [the tool skips it: %s]' % s.skip if s.skip else ''))
        for i, _w in stale:
            if not sites_by_header:
                say('%s is out of date: it differs from what the tool writes (a hand edit, a moved cvar, or a missing shard): run `py -I tools\\compile\\cvar_shard.py`' % shard_path(i))
        bad = bool(sites_by_header) or bool(stale)
        say('cvar_shard --check: %d definition(s) left in headers, %d shard(s) out of date' % (total, len(stale)))
        return 1 if bad else 0
    for h, newtext in sorted(rewrites.items()):
        old = tree.rd(h)
        write(tree, h, newtext)   # (read with newline='': the file's own line endings are in newtext)
    for i, want in stale:
        write(tree, shard_path(i), want)
    say('cvar_shard: %d definition(s) found in %d header(s); %d moved to %d shard(s) (%d shard file(s) written); %d skipped'
        % (total, len(sites_by_header), total - len(skipped), SHARDS, len(stale), len(skipped)))
    return 1 if skipped else 0


