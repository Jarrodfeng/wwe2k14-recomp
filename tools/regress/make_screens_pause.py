"""Build tools/input_scripts/screens_pause.txt from bench_lesnar_bryan.txt (Session 8, task 16).

Screenshot-diff capture route for the pause menu's frozen 3D scene (docs/session6_notes.md run 087: paused frames
are identical). Same input as the bench route up to the b_match600 screenshot (600 frames after the M3.PAC open),
then START opens the pause menu and two screenshots of the paused scene are taken 240 frames apart (they must be
identical within the run: a frozen scene). Run it with --wwe2k14_fixed_seed=1234 so the match (CPU vs CPU) is the
same game in every run at that moment (docs/systems/determinism.md: same-seed 60 fps pairs are identical or nearly at
b_match600; divergence only starts ~1,640 match frames in). The regress route 'pause' (tools/regress/checks_screens.py)
launches it that way.

Usage: py tools/regress/make_screens_pause.py
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "tools" / "input_scripts" / "bench_lesnar_bryan.txt"
DST = ROOT / "tools" / "input_scripts" / "screens_pause.txt"

TAIL = [
    "# Pause menu: START, let the menu settle, two shots of the frozen scene 240 frames apart.",
    "press START",
    "wait_frames 240",
    "screenshot p_pause240",
    "wait_frames 240",
    "screenshot p_pause480",
    "log screens: pause shots done",
    "# The screenshot is saved on another thread: wait before quitting (Session 7c run 174).",
    "wait_frames 60",
    "quit",
]


def main():
    lines = SRC.read_text(encoding="utf-8").splitlines()
    try:
        i = lines.index("screenshot b_match600")
    except ValueError:
        sys.exit(f"{SRC}: no 'screenshot b_match600' line (the bench route changed; update this generator)")
    out = [
        "# Screenshot-diff route (Session 8 task 16): bench_lesnar_bryan.txt up to b_match600, then the pause menu.",
        "# Generated by tools/regress/make_screens_pause.py (do not edit by hand). Run with --wwe2k14_fixed_seed=1234.",
    ]
    out += [x for x in lines[:i + 1] if not x.startswith("# Generated by")]
    out += TAIL
    DST.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {DST} ({len(out)} lines)")


if __name__ == "__main__":
    main()
