"""tools/regress plugin: screenshot diff against references (Session 8, task 16). Docs: docs/harness/screens.md.

Adds the check 'screens' to the routes with fixed capture points:
  selftest  title / storage_notice / main_menu   (animated backgrounds: loose whole-frame + tight stable-pixel mask)
  logo      logo_grid / editor / stamp_categories / after_lettering   (pixel-identical in every A/A pair: ~0)
  pause     (opt-in route, see below) p_pause240 / p_pause480 = the pause menu's frozen 3D scene: vs references,
            and the two shots of one run must be identical (frozen scene)
Each label of the route's references (out\\harness\\screenshots\\refs\\manifest.json, built with
`py tools\\bench\\shot_refs.py build ROUTE --runs ...`) gives one result 'screens.LABEL'. A run at another
resolution (e.g. --extra-args="--wwe2k14_preset_4k60=true") is downscaled and judged with the resampling allowance
(the run-175 method): it passes when it looks the same beyond resampling. No references for a route = 'warn'.

The 'pause' route (tools/input_scripts/screens_pause.txt, generated by tools/regress/make_screens_pause.py: Lesnar vs
Bryan with --wwe2k14_fixed_seed=1234, START 600 frames into the match, ~4 min) is opt-in so a default regress pass
keeps its length: it is registered only when the command line names it (`--only selftest,logo,pause`,
`--runs pause=NNN`, `--list`, or argparse's prefixes of them such as `--onl`) or PAUSE_DEFAULT below is True.
Its screenshots b_brock100 / b_second440 / b_match600 are taken (the route check) but not compared: the manifest's
exclude list for the route keeps them out of the references.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, 'tools', 'bench'))
import shot_refs  # noqa: E402

PAUSE_DEFAULT = False
SCREEN_ROUTES = ('selftest', 'logo')
PAUSE_ROUTE = dict(
    script='screens_pause.txt', extra='--wwe2k14_preset_1440p60=false --wwe2k14_fixed_seed=1234', timeout=720,
    shots=['b_arena', 'b_brock100', 'b_second440', 'b_match600', 'p_pause240', 'p_pause480'],
    checks=['flags', 'hard_fails', 'clean_exit', 'screenshots', 'screens'],
    frozen=[('p_pause240', 'p_pause480')])


def _opt(tok):
    """'--only' / '--runs' / '--list' for a token argparse would read as that option (it accepts unique prefixes:
    --onl, --ru, --li; none of regress.py's other options starts with --o, --r or --l), else None."""
    key = tok.split('=', 1)[0]
    if len(key) > 2 and key.startswith('--'):
        for full in ('--only', '--runs', '--list'):
            if full.startswith(key):
                return full
    return None


def _pause_wanted(argv):
    """True when the regress command line names the 'pause' route (or asks for --list)."""
    vals = []
    for i, a in enumerate(argv):
        o = _opt(a)
        if o == '--list':
            return True
        if o and '=' in a:
            vals.append(a.split('=', 1)[1])
        elif o:
            vals.extend(x for x in argv[i + 1:i + 2])
            if o == '--runs':  # --runs takes several ROUTE=N values
                for x in argv[i + 2:]:
                    if x.startswith('--'):
                        break
                    vals.append(x)
    for v in vals:
        for part in v.split(','):
            if part.strip().split('=')[0] == 'pause':
                return True
    return False


def register(api):
    @api.check('screens')
    def screens(ctx):
        out = []
        res, note = shot_refs.check_run(ctx.route_name, ctx.run, ctx.captures, ctx.logs)
        if not res:
            out.append(api.Result('screens', 'warn', note))
        else:
            for label, st, txt in res:
                out.append(api.Result('screens.' + label, st, txt))
            n_ok = sum(st == 'pass' for _, st, _ in res)
            out.append(api.Result('screens', 'info', '%d/%d labels within thresholds' % (n_ok, len(res))))
            if note:
                out.append(api.Result('screens.settings', 'info', note))
        for a, b in ctx.route.get('frozen', []):
            ok, txt = shot_refs.frozen_check(ctx.run, a, b, ctx.captures)
            out.append(api.Result('screens.frozen', 'pass' if ok else 'fail', txt))
        return out

    for r in SCREEN_ROUTES:
        if r in api.routes and 'screens' not in api.routes[r]['checks']:
            api.routes[r]['checks'].append('screens')
    if PAUSE_DEFAULT or _pause_wanted(sys.argv[1:]):
        api.routes.setdefault('pause', PAUSE_ROUTE)
