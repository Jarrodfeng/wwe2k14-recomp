"""S102 W3: build the offline reference for the differential test from the LOCAL generated code (generated\\default, gitignored, never committed).

Writes two files under --out (default out\\s102\\w3 of the main checkout, also gitignored):
  ref_funcs.inc   the recompiled sub_82BB5BE8, sub_82BB53D0, __savegprlr_29 and __restgprlr_29 as plain `extern "C" void __imp__<name>(...)`
                  (DEFINE_REX_FUNC turned into a plain definition so the test owns the public names: it routes sub_82BB53D0 itself, as the
                  game's hook does)
  ref_callees.inc X(name, 0xADDR) lines for every function those bodies call (the test makes a recording stub for each), plus the handlers
                  of the native table in src\\nf\\replay_native.h

    py -I tools\\w3\\diff\\extract_ref.py --gen C:\\Users\\Jarrod\\wwe2k14-recomp\\generated\\default [--out DIR]

Exit 2 when a function is not found in the generated code (loud: a test with no reference must never pass).
"""
import argparse
import glob
import os
import re
import sys

FUNCS = ['sub_82BB5BE8', 'sub_82BB53D0', '__savegprlr_29', '__restgprlr_29']
HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(HERE))), 'src', 'nf', 'replay_native.h')


def find_func(gen, name, files):
    marker = 'DEFINE_REX_FUNC(%s) {' % name
    for p in files:
        t = open(p, encoding='utf-8', errors='replace').read()
        i = t.find(marker)
        if i >= 0:
            j = t.find('\n}\n', i)
            return t[i:j + 3]
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--gen', required=True)
    ap.add_argument('--out', default=r'C:\Users\Jarrod\wwe2k14-recomp\out\s102\w3')
    a = ap.parse_args()
    files = sorted(glob.glob(os.path.join(a.gen, 'wwe2k14_recomp.*.cpp')))
    if not files:
        print('extract_ref: no generated code under %s' % a.gen)
        return 2
    os.makedirs(a.out, exist_ok=True)
    bodies = []
    for name in FUNCS:
        t = find_func(a.gen, name, files)
        if t is None:
            print('extract_ref: %s not found in the generated code' % name)
            return 2
        t = t.replace('DEFINE_REX_FUNC(%s) {' % name, 'extern "C" void __imp__%s([[maybe_unused]] PPCContext& __restrict ctx, uint8_t* base) {' % name, 1)
        bodies.append(t)
    text = '\n'.join(bodies)
    open(os.path.join(a.out, 'ref_funcs.inc'), 'w').write('// generated by tools/w3/diff/extract_ref.py from the local generated code; never committed\n' + text)
    callees = set(re.findall(r'\b((?:sub_[0-9A-F]{8})|(?:__[A-Za-z0-9_]+))\(ctx, base\)', text))
    callees -= set(FUNCS)
    # the handlers of the native table
    hdr = open(HEADER, encoding='utf-8').read()
    callees |= set(re.findall(r'T\(\d+, Call, (sub_[0-9A-F]{8})\)', hdr))
    callees -= {'sub_82BB53D0', 'sub_82BB5BE8'}
    lines = []
    for n in sorted(callees):
        m = re.match(r'sub_([0-9A-F]{8})$', n)
        lines.append('X(%s, 0x%s)' % (n, m.group(1) if m else '0'))
    open(os.path.join(a.out, 'ref_callees.inc'), 'w').write('\n'.join(lines) + '\n')
    print('extract_ref: %d functions, %d callee stubs -> %s' % (len(FUNCS), len(callees), a.out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
