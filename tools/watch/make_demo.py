"""Builds tools/watch/demo_lesnar_watch.txt: the Lesnar vs Bryan benchmark route plus watch / snap / mark lines
(Session 8 task 10 demonstration of src/guest_watch.h).

    py tools/watch/make_demo.py

Watched (addresses from the system maps, which got them from the code index and live logs):
  0x8392DC40  frame-rate word (docs/systems/frame_pacing.md): 60 in menus/match, 30 in entrances
  0x836F3940  scene/phase word (docs/systems/match_state.md, ai_decision.md): 1 boot, 4 match load + entrances, 1 ring
  0x836F3928  match clock (match_state.md): +1 per frame once the match runs; a hot word, exercises the rate limit
  0x83767B6C  watch_zero (the Session 3 alias) on the referee judge pointer (match_state.md / states.toml 'judge')
Snapped every frame:
  timing  0x8392DC38..+128  timing block holding the frame-rate word and its step fields (frame_pacing.md)
  gvals   0x836F3900..+176  globals around the clock and scene word (determinism.md 'gvals')
Marks: 1 = 343.bik2 opens (Brock's entrance), 2 = 324.bik2 opens (Bryan's), 3 = M3.PAC opens (match).
The route ends ~10 s into the match (after b_match600) to keep the run short.

Run (one line):
  pwsh -NoProfile -Command "& C:/Users/Jarrod/wwe2k14-recomp/tools/bench/run_list.ps1 -Scripts @('..\\..\\..\\tools\\watch\\demo_lesnar_watch.txt')"
Then: py tools/watch/watch_report.py RUN ; py tools/watch/snap_report.py RUN --mark 1
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SOURCE = ROOT / 'tools' / 'input_scripts' / 'bench_lesnar_bryan.txt'
OUT = HERE / 'demo_lesnar_watch.txt'

ARM = [
    '# --- task 10 demo: watches and snapshots (src/guest_watch.h) ---',
    'watch 0x8392DC40 4 any',
    'watch 0x836F3940 4 any',
    'watch 0x836F3928 4 any',
    'watch_zero 0x83767B6C',
    'snap 0x8392DC38:128 timing',
    'snap 0x836F3900:176 gvals',
]
MARKS = {
    'wait_file 343.bik2': 'mark 1 entrance_343',
    'wait_file 324.bik2': 'mark 2 entrance_324',
    'wait_file M3.PAC': 'mark 3 match',
}
END = [
    'wait_frames 600',
    'unwatch',
    'unsnap',
    'log bench: done',
    'wait_frames 60',
    'quit',
]


def main():
    lines = SOURCE.read_text(encoding='utf-8').splitlines()
    out = [
        '# Session 8 task 10 demo route, GENERATED by tools/watch/make_demo.py from',
        '# tools/input_scripts/bench_lesnar_bryan.txt (edit the generator, not this file).',
        '# Watches the frame-rate word, the scene word, the match clock and (watch_zero) the judge pointer;',
        '# snaps the timing block and the 0x836F39xx globals; marks the two entrances and the match.',
    ]
    armed = False
    header = True
    for line in lines:
        if header and line.startswith('#'):
            continue  # the source's own header comment
        header = False
        if line.strip() == 'log bench: done':
            out.extend(END)
            break
        out.append(line)
        if not armed and line.startswith('log bench: start'):
            out.extend(ARM)
            armed = True
        for prefix, mark in MARKS.items():
            if line.startswith(prefix):
                out.append(mark)
        if line.startswith('screenshot b_match600'):
            out.extend(END)
            break
    if not armed:
        sys.exit('make_demo: no "log bench: start" line in ' + str(SOURCE))
    OUT.write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print('wrote', OUT, len(out), 'lines')


if __name__ == '__main__':
    main()
