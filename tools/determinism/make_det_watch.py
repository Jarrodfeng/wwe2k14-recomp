"""Write tools/determinism/determinism_lesnar_watch.txt (Session 8, task A).

    py tools/determinism/make_det_watch.py [--addr 0xA90D58F0,0xA8F881D0] [--after b_match600] [--until d_match2400]

The determinism route (determinism_lesnar.txt, from make_det_lesnar.py) plus `watch ADDR 4 change` steps (src/guest_watch.h)
right after the screenshot named by --after, and `unwatch` right after the screenshot named by --until. Default
addresses: the x floats (+0) of the two wrestlers' position objects (character +176) that sub_82666310 reads for the
pairwise distance table. They are heap addresses, seen in runs 263, 268 and 269 (det dumps: slot 0 at 0xA90BAFB0 ->
+176 = 0xA90D58F0; slot 1 at 0xA8F77710 -> +176 = 0xA8F881D0) but not in run 260 (another layout): check the a / b
columns of the run's fp_NNN.tsv (--wwe2k14_fp_probe=true) before trusting a result.
Arming a watch stops the script thread for ~40-60 ms (tools/watch/README.md): the watched run's timing is perturbed
at that frame.
"""
import argparse
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(REPO, 'tools', 'input_scripts', 'determinism_lesnar.txt')
DST = os.path.join(HERE, 'determinism_lesnar_watch.txt')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--addr', default='0xA90D58F0,0xA8F881D0')
    ap.add_argument('--after', default='b_match600')
    ap.add_argument('--until', default='d_match2400')
    ap.add_argument('--out', default=DST, help='output route (default tools/determinism/determinism_lesnar_watch.txt)')
    args = ap.parse_args()
    addrs = [a.strip() for a in args.addr.split(',') if a.strip()]
    if not 1 <= len(addrs) <= 4:
        raise SystemExit('1 to 4 addresses (hardware slots)')
    lines = open(SRC, encoding='utf-8').read().splitlines()
    out, armed, disarmed = [], False, False
    out.append('# Generated by tools/determinism/make_det_watch.py from determinism_lesnar.txt (task A): watches on %s'
               % ', '.join(addrs))
    for line in lines:
        out.append(line)
        if line.strip() == 'screenshot ' + args.after:
            out += ['watch %s 4 change' % a for a in addrs]
            armed = True
        elif line.strip() == 'screenshot ' + args.until:
            out.append('unwatch')
            disarmed = True
    if not armed or not disarmed:
        raise SystemExit('screenshot %s / %s not found in %s' % (args.after, args.until, SRC))
    with open(args.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print("wrote", args.out)


if __name__ == '__main__':
    main()
