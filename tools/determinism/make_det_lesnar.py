"""Build tools/input_scripts/determinism_lesnar.txt from bench_lesnar_bryan.txt (Session 8, task 8b).

Same route (Brock Lesnar vs Daniel Bryan, CPU vs CPU once the match starts), with more screenshots for frame
comparison: the match window's single 'wait_frames 3000 / screenshot b_match3600' is split into steps of STEP
frames, each followed by a screenshot d_matchNNNN (NNNN = frames after the M3.PAC open + 600). Everything before
it is unchanged, so input timing matches the bench route exactly.

Usage: py tools/determinism/make_det_lesnar.py [--step 300]
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "tools" / "input_scripts" / "bench_lesnar_bryan.txt"
DST = ROOT / "tools" / "input_scripts" / "determinism_lesnar.txt"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--step", type=int, default=300)
    args = ap.parse_args()
    lines = SRC.read_text(encoding="utf-8").splitlines()
    try:
        i = lines.index("wait_frames 3000")
    except ValueError:
        sys.exit(f"{SRC}: no 'wait_frames 3000' line (the bench route changed; update this generator)")
    if i + 1 >= len(lines) or lines[i + 1] != "screenshot b_match3600":
        sys.exit(f"{SRC}: 'wait_frames 3000' is not followed by 'screenshot b_match3600'")
    out = [
        "# Determinism route (Session 8 task 8b): bench_lesnar_bryan.txt with a screenshot every "
        f"{args.step} match frames.",
        "# Generated by tools/determinism/make_det_lesnar.py (do not edit by hand).",
    ]
    out += [l for l in lines[:i] if not l.startswith("# Generated by")]
    done = 0
    while done < 3000:
        step = min(args.step, 3000 - done)
        done += step
        out.append(f"wait_frames {step}")
        out.append(f"screenshot d_match{600 + done:04d}")
    out += lines[i + 2:]
    DST.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {DST} ({len(out)} lines, {3000 // args.step} match screenshots)")


if __name__ == "__main__":
    main()
