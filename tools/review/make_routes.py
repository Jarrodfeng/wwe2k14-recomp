"""Generate review route variants from the bench routes (Session 8, task 4). Never edits the bench routes.

A review route is a bench route (tools/input_scripts/bench_*.txt, itself generated by build_bench_routes.py) with
the part after the second entrance's anchor replaced by review lines:
  - "clip_start NAME 60 1" / "clip_stop NAME": in-game clip capture (src/clip_capture.h; active only with
    --wwe2k14_clip_dir, which record.py's default in-game mode sets): the guest output at internal resolution;
  - "log review: clip_start NAME" / "log review: clip_stop NAME": anchors in the log (compose.py reads their frame
    numbers); in record.py's desktop fallback mode it starts / stops an ffmpeg desktop capture on these lines;
  - "screenshot rv_NAME_tSS": native-resolution stills at the same moments;
and the run quits shortly after the match clip instead of playing 60 s of match.

Entrance waits are in seconds and converted to guest frames per arm: entrances run at 30 fps at default settings
and at 60 fps with the 1440p / 4K presets (--wwe2k14_entrance_60fps), so the same moment needs twice the frames.
The match runs at 60 fps in every arm.

    py tools\\review\\make_routes.py --base bryan --entrance-fps 30 --out out\\harness\\review\\routes\\review_bryan_e30.txt
    py tools\\review\\make_routes.py --all          writes every route x entrance-fps variant into out\\harness\\review\\routes\\
"""
import argparse
import os
import re

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
ROUTES_OUT = os.path.join(REPO, 'out', 'harness', 'review', 'routes')

# base route -> bench route file. 'second' is the second entrant's tron: the review clip anchors on it.
BASES = {
    'bryan': {'file': 'tools/input_scripts/bench_lesnar_bryan.txt', 'second': '324',
              'what': "Bryan's entrance (ramp pan, wide crowd) + match"},
    'taker': {'file': 'tools/input_scripts/bench_taker_wm.txt', 'second': '103',
              'what': "Undertaker's entrance in WrestleMania Moment (CH103 crowd stretch) + match"},
}

# Moments, in seconds after the anchor. Entrance clip: 6 s -> 24 s after the second tron opens (run 178's
# b_second440 = 14.7 s at 30 fps shows Bryan on the stage with the crowd; run 173's shows CH103's wide crowd).
ENTRANCE = {'clip': ('e2', 6.0, 24.0), 'stills': [9.0, 14.7, 20.0]}
# Match: clip 5 s -> 20 s after M3.PAC (run 178's b_match600 = 10 s shows a medium in-ring shot with crowd).
MATCH = {'clip': ('match', 5.0, 20.0), 'stills': [10.0, 15.0]}


# In-game clip arguments (src/clip_capture.h `clip_start NAME [FPS] [SCALE]`): the guest output at the internal
# resolution, 60 fps. The clip lines do nothing unless the run sets --wwe2k14_clip_dir (record.py's in-game mode
# does), so the same route still works with desktop capture.
CLIP_ARGS = '60 1'


def section(prefix, spec, fps, clip_args=None):
    """Lines for one anchored section: waits in frames at `fps`, clip start/stop and stills, in time order."""
    name, c0, c1 = spec['clip']
    clip_args = clip_args or CLIP_ARGS
    events = [(c0, 0, f'log review: clip_start {prefix}{name}'), (c0, 0.5, f'clip_start {prefix}{name} {clip_args}'),
              (c1, 2, f'clip_stop {prefix}{name}'), (c1, 2.5, f'log review: clip_stop {prefix}{name}')]
    for t in spec['stills']:
        events.append((t, 1, f'screenshot rv_{prefix}{name}_t{t:04.1f}'.replace('.', 'p')))
    events.sort()
    out, now = [], 0
    for t, _, line in events:
        frames = int(round(t * fps)) - now
        if frames > 0:
            out.append(f'wait_frames {frames}')
            now += frames
        out.append(line)
    return out


def build(base, entrance_fps, clip_args=None):
    info = BASES[base]
    src = os.path.join(REPO, info['file'])
    with open(src, encoding='utf-8') as f:
        lines = f.read().splitlines()
    anchor = next(i for i, l in enumerate(lines) if l.strip() == f"log scene=tron_{info['second']}")
    loadhd = next(i for i in range(anchor, len(lines)) if lines[i].startswith('wait_file LOADHD.PAC'))
    match = next(i for i in range(loadhd, len(lines)) if lines[i].strip() == 'log scene=match')
    head = [f'# Review route ({base}, entrances at {entrance_fps} fps): GENERATED by tools/review/make_routes.py',
            f"# from {info['file']} - {info['what']}. Do not edit; edit the generator.",
            '# In-game clips: clip_start / clip_stop (need --wwe2k14_clip_dir). Desktop fallback: record.py tails the',
            '# game log for "review: clip_start/clip_stop" and records the desktop meanwhile.']
    body = [l for l in lines[:anchor + 1] if not l.startswith('# Generated by') and 'do not edit by hand' not in l]
    body.append(f'log review: anchor e2 (entrance fps {entrance_fps})')
    body += section('', ENTRANCE, entrance_fps, clip_args)
    body += lines[loadhd:match + 1]
    body.append('log review: anchor match')
    body += section('', MATCH, 60, clip_args)
    body += ['# Screenshots are saved on another thread: wait ~60 frames before quitting (run 174).',
             'wait_frames 90', 'log review: done', 'quit']
    for l in body:
        if re.search(r'[\x00-\x08\x0b\x0c\x0e-\x1f]', l):
            raise SystemExit(f'control byte in generated line: {l!r}')
    return '\n'.join(head + body) + '\n'


def write(base, entrance_fps, out, clip_args=None):
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(build(base, entrance_fps, clip_args))
    return out


def default_path(base, entrance_fps, clip_args=None):
    tag = '' if not clip_args or clip_args == CLIP_ARGS else '_c' + clip_args.replace(' ', '_').replace('.', 'p')
    return os.path.join(ROUTES_OUT, f'review_{base}_e{entrance_fps}{tag}.txt')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--base', choices=sorted(BASES))
    ap.add_argument('--entrance-fps', type=int, default=30, choices=[30, 60])
    ap.add_argument('--out')
    ap.add_argument('--all', action='store_true')
    a = ap.parse_args()
    if a.all:
        for b in BASES:
            for fps in (30, 60):
                print(write(b, fps, default_path(b, fps)))
    elif a.base:
        print(write(a.base, a.entrance_fps, a.out or default_path(a.base, a.entrance_fps)))
    else:
        ap.error('--base or --all')


if __name__ == '__main__':
    main()
