#!/usr/bin/env python3
r"""S103 lane J1: tools\harvest\sweep_routes.txt -> the route scripts of the harvest sweep (out\harvest\routes\, scratch), the start count and the run commands. 0 game runs.

  py -I tools\harvest\make_routes.py [--list] [--check] [--write] [--only ID,ID] [--commands]
    --list      the table: id, kind, windows, estimated seconds; the totals (STARTS, windows, estimated hours)
    --check     every wrap script exists, every arena has its bgNN.pac under game_data\extracted\pac\bg (when the game files are present), no duplicate id; exit 1 on a problem
    --write     write the generated routes to out\harvest\routes\harvest_<ID>.txt
    --commands  print one run_list command per start, then the harvest command per window (what the main session pastes)
A generated arena route (KIND arena): launch override --wwe2k14_launch_arena=N, Brock (343) then Bryan (324) CPU v CPU, fixed seed 1; one 120-frame recording at Brock's entrance step 15
(+30 frames, the entrance's set / lights / pyro / fog look), one at the match clock +300 (the match look). A wrap route copies an existing Session 101 / 103 route, drops the mirror / owner
flags, adds the capture flags and records a window after every `mark`. The capture flags are the file's header (sweep_routes.txt)."""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
LIST = os.path.join(HERE, 'sweep_routes.txt')
OUT = os.path.join(ROOT, 'out', 'harvest', 'routes')
CAPTURE_FLAGS = '--wwe2k14_rdr_capture=true --wwe2k14_scene_records=true --wwe2k14_scene_light_states=true --wwe2k14_fixed_seed=1 --vulkan_stored_pipelines_at_boot=false'
DROP = re.compile(r'--wwe2k14_(rdr_scene=\S*|rdr_owner=\S*|s101_promotions=\S*|rdr_ring_d3=\S*|rdr_stage_vis=\S*|rdr_scene_census=\S*|rdr_scene_sheet_every=\S*|d3d_owned=\S*|dump_stage_page=\S*)')
WINDOW_FRAMES = 120
WINDOW_WAIT = 140


def parse(path=LIST):
    rows = []
    for ln, line in enumerate(open(path, encoding='utf-8'), 1):
        if not line.strip() or line.startswith('#'):
            continue
        f = [x.strip() for x in line.rstrip('\n').split(' | ')]
        kind = f[1]
        r = dict(id=f[0], kind=kind, line=ln, extra='')
        if kind == 'arena':
            r['arena'] = int(f[2])
            rest = f[3:]
            if rest and rest[0].startswith('extra='):
                r['extra'] = rest[0][6:]
                rest = rest[1:]
            r['windows'], r['est'], r['covers'] = rest[0], int(rest[1]), rest[2]
        elif kind == 'type':
            r['type'], r['arena'], r['participants'] = int(f[2]), int(f[3]), f[4]
            r['windows'], r['est'], r['covers'] = f[5], int(f[6]), f[7]
        elif kind == 'wrap':
            r['script'], r['windows'], r['est'], r['covers'] = f[2], f[3], int(f[4]), f[5]
        else:
            raise SystemExit('%s:%d: unknown kind %r' % (path, ln, kind))
        r['windows'] = [w.strip() for w in r['windows'].split(',')] if kind != 'wrap' else [r['windows']]
        rows.append(r)
    return rows


def win_cvars(label):
    return ['cvar wwe2k14_rdr_capture_label %s' % label, 'cvar wwe2k14_rdr_capture_frames %d' % WINDOW_FRAMES, 'wait_frames %d' % WINDOW_WAIT]


def gen_arena(r):
    n = r['arena']
    wl = [w.split(':')[0] for w in r['windows']]
    flags = '--wwe2k14_launch=lesnar_bryan --wwe2k14_launch_arena=%d --wwe2k14_launch_participants=343,324 %s %s' % (n, CAPTURE_FLAGS, r['extra'])
    out = ['# harness: flags ' + flags.strip(),
           '# S103 J1 harvest sweep %s (generated by tools\\harvest\\make_routes.py from sweep_routes.txt): arena %d, entrance + match, capture windows %s. Mirror off: the game draws alone.' % (r['id'], n, ', '.join(wl)),
           'on_fail quit', 'log bench: start scene harvest_%s' % r['id'], 'include boot_to_menu', 'wait_file INGAMELUA.PAC 1800', 'log bench: match launched',
           'wait_file BG%02d.PAC 900' % n, 'log scene=entrances', 'mark 1 entrances',
           'wait_state entrance_step_0 >=15 30000 2', 'log scene=step15', 'mark 2 step15', 'wait_frames 30'] + win_cvars(wl[0]) + \
          ['wait_state match_clock >0 30000', 'log scene=match', 'mark 3 match_clock', 'wait_frames 300'] + win_cvars(wl[1]) + ['log bench: done', 'wait_frames 10', 'quit']
    return '\n'.join(out) + '\n'


def gen_type(r):
    wl = [w.split(':')[0] for w in r['windows']]
    flags = '--wwe2k14_launch=@quick --wwe2k14_launch_skip_entrances=true --wwe2k14_launch_arena=%d --wwe2k14_quick_type=%d --wwe2k14_launch_participants=%s %s' % (r['arena'], r['type'], r['participants'], CAPTURE_FLAGS)
    out = ['# harness: flags ' + flags, '# harness: realtime',
           '# S103 J1 harvest sweep %s: match type %d in arena %d (participants %s), capture window %s at match clock +300. Mirror off.' % (r['id'], r['type'], r['arena'], r['participants'], wl[0]),
           'on_fail quit', 'log bench: start scene harvest_%s' % r['id'], 'include boot_to_menu', 'wait_file INGAMELUA.PAC 3600', 'wait_state seq 9 3600 30', 'wait_state match_clock >0 36000',
           'log scene=match', 'mark 1 match_clock', 'wait_frames 300'] + win_cvars(wl[0]) + ['log bench: done', 'wait_frames 10', 'quit']
    return '\n'.join(out) + '\n'


def gen_wrap(r):
    src = os.path.join(ROOT, 'tools', 'input_scripts', r['script'])
    lines = open(src, encoding='utf-8').read().split('\n')
    out, n, seen_header = [], 0, False
    for line in lines:
        m = re.match(r'^# harness: flags (.*)$', line)
        if m and not seen_header:
            seen_header = True
            kept = DROP.sub('', m.group(1))
            kept = re.sub(r'--wwe2k14_(fixed_seed|vulkan_stored_pipelines_at_boot)=\S*', '', kept)
            out.append('# harness: flags ' + re.sub(r'\s+', ' ', kept).strip() + ' ' + CAPTURE_FLAGS)
            continue
        out.append(line)
        mm = re.match(r'^mark (\d+)\s*(\S*)', line)
        if mm:
            n += 1
            out += ['wait_frames 60'] + win_cvars('harvest_%s_m%s_%s' % (r['id'].lower(), mm.group(1), mm.group(2) or 'mark'))
    if not seen_header:   # a route with no harness line gets one (its own flags come from its caller)
        out.insert(0, '# harness: flags ' + CAPTURE_FLAGS)
    return '\n'.join(out), n


def build(r):
    if r['kind'] == 'arena':
        return gen_arena(r), 2
    if r['kind'] == 'type':
        return gen_type(r), 1
    text, n = gen_wrap(r)
    return text, n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--list', action='store_true')
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--commands', action='store_true')
    ap.add_argument('--only', default='')
    a = ap.parse_args()
    rows = parse()
    if a.only:
        keep = set(a.only.split(','))
        rows = [r for r in rows if r['id'] in keep]
    bad = []
    ids = [r['id'] for r in rows]
    if len(ids) != len(set(ids)):
        bad.append('duplicate ids')
    windows = 0
    est = 0
    kinds = {}
    for r in rows:
        text, nwin = build(r)
        r['text'], r['nwin'] = text, nwin
        windows += nwin
        est += r['est']
        kinds[r['kind']] = kinds.get(r['kind'], 0) + 1
        if r['kind'] == 'wrap' and not os.path.exists(os.path.join(ROOT, 'tools', 'input_scripts', r['script'])):
            bad.append('%s: script %s missing' % (r['id'], r['script']))
        if r['kind'] in ('arena', 'type'):
            game = os.path.join(ROOT, 'game_data', 'extracted', 'pac', 'bg')
            main_game = os.environ.get('RDR_MAIN_CHECKOUT')
            for g in [game] + ([os.path.join(main_game, 'game_data', 'extracted', 'pac', 'bg')] if main_game else []):
                if os.path.isdir(g):
                    if not any(f.lower() == 'bg%02d.pac' % r['arena'] for f in os.listdir(g)):
                        bad.append('%s: bg%02d.pac not under %s' % (r['id'], r['arena'], g))
                    break
    if a.list or not (a.check or a.write or a.commands):
        for r in rows:
            print('%-4s %-6s %-4s windows %-2d est %4d s  %s' % (r['id'], r['kind'], r.get('arena', ''), r['nwin'], r['est'], r['covers'][:70]))
    print('STARTS %d (%s), capture windows %d, estimated %.1f h of game time' % (len(rows), ', '.join('%s %d' % kv for kv in sorted(kinds.items())), windows, est / 3600.0))
    if a.write:
        os.makedirs(OUT, exist_ok=True)
        for r in rows:
            with open(os.path.join(OUT, 'harvest_%s.txt' % r['id']), 'w', encoding='utf-8', newline='\n') as f:
                f.write(r['text'])
        print('wrote %d routes to %s' % (len(rows), OUT))
    if a.commands:
        for r in rows:
            print(r"& .\tools\bench\run_list.ps1 -Scripts @('out\harvest\routes\harvest_%s.txt')" % r['id'])
        for r in rows:
            if r['kind'] in ('arena', 'type'):
                for w in r['windows']:
                    lab, look = w.split(':')
                    print(r'py -I tools\harvest\choice_harvest.py out\captures\%s:%d --scene %s --look %s --every 1' % (lab, r['arena'], r['id'].lower(), look))
    for b in bad:
        print('PROBLEM', b)
    return 1 if (a.check and bad) else 0


if __name__ == '__main__':
    sys.exit(main())
