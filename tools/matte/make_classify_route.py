"""Session 16 item 7: write tools/input_scripts/short/matte_classify.txt, a route that reaches the post-match freeze (the
scene is redrawn identically every frame there) and takes one matte dump with nothing skipped, then one per vertex
shader with only that shader skipped (gpu_debug_skip_vertex_shader), so tools/matte/classify.py can tell which shader
draws what (wrestlers, referee, ring, crowd).

    py tools/matte/make_classify_route.py HASH,HASH,...
"""
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, 'tools', 'input_scripts', 'short', 'matte_classify.txt')

HEAD = """# Session 16 item 7 (GENERATED by tools/matte/make_classify_route.py): shader classification in the post-match freeze.
# Use with --wwe2k14_launch=lesnar_bryan --wwe2k14_launch_skip_entrances=true --wwe2k14_matte=depth. CPU match
# fast-forwarded to the finish + 4,000 frames (the freeze), then screenshot cf_base (with its matte dump) and one
# screenshot cf_NN per vertex shader with only that shader skipped. on_fail quit.
on_fail quit
log cf: start
wait_file SaveData.Dat 36000
wait_frames 160
set 0x0010 0 0 0 0 -1636 -1137
wait_frames 10
set 0x0000 0 0 0 0 -1069 -1234
wait_frames 66
set 0x1000 0 0 0 0 -770 -1136
wait_frames 10
set 0x0000 0 0 0 0 -770 -1136
wait_file MNUIHD.PAC 36000
wait_file INGAMELUA.PAC 36000
wait_state match_clock !=0 36000 2
wait_state 0x8376ACCC !=0 400000 2
log cf: finish
wait_frames 4000
log cf: in the freeze
screenshot cf_base
wait_frames 20
"""


def main():
    hashes = [h for h in sys.argv[1].split(',') if h]
    # Optional second argument: a free-camera pose X,Y,Z,YAW,PITCH,FOV for the freeze cam (run with
    # --wwe2k14_cinecam=true --wwe2k14_cinecam_freeze=true); without it the game's own frozen shot is used.
    pose = sys.argv[2] if len(sys.argv) > 2 else ''
    head = HEAD
    if pose:
        head = head.replace('log cf: in the freeze\n', 'log cf: in the freeze\ncvar wwe2k14_cinecam_on true\n'
                            'cvar wwe2k14_cinecam_test_pose %s\nwait_frames 30\n' % pose)
    lines = [head.rstrip('\n')]
    for i, h in enumerate(hashes):
        lines += ['log cf: %02d %s' % (i, h), 'cvar gpu_debug_skip_vertex_shader %s' % h, 'wait_frames 4',
                  'screenshot cf_%02d' % i, 'wait_frames 20']
    lines += ['cvar gpu_debug_skip_vertex_shader 0', 'wait_frames 4', 'screenshot cf_after', 'wait_frames 30',
              'log cf: end', 'quit']
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(OUT, len(hashes), 'shaders')


if __name__ == '__main__':
    main()
