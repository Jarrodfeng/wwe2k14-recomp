"""Short route variants for timed questions (Session 8): a copy of a route that stops right after the scene you
measure, so a timed run doesn't play the rest of the route (the rest of an entrance, the match, the quit).

    py tools\\input_scripts\\make_short.py ROUTE --after-file TEXT --frames N [--name SUFFIX]
    py tools\\input_scripts\\make_short.py ROUTE --until-shot LABEL [--name SUFFIX]
    py tools\\input_scripts\\make_short.py --standard          (regenerates the standard variants below)

--after-file TEXT --frames N: cut after the first top-level "wait_file TEXT ..." line, then wait N guest frames.
--until-shot LABEL: cut after "screenshot LABEL". Both then wait 60 frames (an async screenshot save must finish before
quit, PLAYBOOK Session 7c) and quit. Output: tools\\input_scripts\\short\\<route>_<suffix>.txt (our own button
sequences, safe to commit). Cutting inside a repeat block is refused (the copy would not load).

Saving: you still boot, go through the menus and play everything before the scene, so a short variant saves the tail
only: about half the run for an entrance question (e.g. the Bryan pan variant skips the rest of his entrance and the
match). Analysis tools treat the end of the data as the end of the last scene.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SHORT = os.path.join(HERE, 'short')

# (route, suffix, mode, value, frames, why)
STANDARD = [
    ('bench_lesnar_bryan.txt', 'pan', 'file', '324.bik2', 600,
     "Bryan's entrance through his ramp pan (+380..+500 frames from his titantron)"),
    ('bench_taker_wm.txt', 'crowd', 'file', '103.bik2', 900,
     "Undertaker's entrance through the heavy crowd/smoke stretch (first ~900 frames, Session 6 heavy window)"),
    ('bench_taker_wm.txt', 'brock', 'file', '343.bik2', 600,
     "Brock's entrance opening shot only (heavy/light variant check)"),
]


def cut(route, mode, value, frames, suffix):
    src = route if os.path.isfile(route) else os.path.join(HERE, route)
    if not os.path.isfile(src):
        raise SystemExit('route not found: %s' % route)
    with open(src, encoding='utf-8') as f:
        lines = f.read().splitlines()
    in_repeat = False
    hit = None
    for i, line in enumerate(lines):
        words = line.split()
        word = words[0] if words else ''
        if word == 'repeat':
            in_repeat = True
        elif word == 'end_repeat':
            in_repeat = False
        if mode == 'file' and word == 'wait_file' and len(words) > 1 and words[1].lower() == value.lower():
            hit = i
        elif mode == 'shot' and line.strip() == 'screenshot %s' % value:
            hit = i
        if hit is not None:
            if in_repeat:
                raise SystemExit('%s line %d is inside a repeat block: cannot cut there' % (route, i + 1))
            break
    if hit is None:
        what = 'wait_file %s' % value if mode == 'file' else 'screenshot %s' % value
        raise SystemExit('%s has no top-level "%s" line' % (route, what))
    stem = os.path.splitext(os.path.basename(src))[0]
    os.makedirs(SHORT, exist_ok=True)
    dst = os.path.join(SHORT, '%s_%s.txt' % (stem, suffix))
    how = ('after "wait_file %s" + %d frames' % (value, frames)) if mode == 'file' else ('after "screenshot %s"' % value)
    tail = []
    if mode == 'file' and frames > 0:
        tail.append('wait_frames %d' % frames)
    tail += ['screenshot s_end', 'wait_frames 60', 'log short route: end (%s)' % how, 'quit']
    body = ['# Generated by tools/input_scripts/make_short.py from %s: stops %s (do not edit; regenerate).' %
            (os.path.basename(src), how)] + lines[:hit + 1] + tail
    text = '\n'.join(body) + '\n'
    with open(dst, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    return dst


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('route', nargs='?')
    ap.add_argument('--after-file')
    ap.add_argument('--frames', type=int, default=0)
    ap.add_argument('--until-shot')
    ap.add_argument('--name', default='')
    ap.add_argument('--standard', action='store_true')
    a = ap.parse_args()
    if a.standard:
        for route, suffix, mode, value, frames, why in STANDARD:
            print('%s  (%s)' % (cut(route, mode, value, frames, suffix), why))
        return 0
    if not a.route or bool(a.after_file) == bool(a.until_shot):
        ap.error('give ROUTE and exactly one of --after-file TEXT / --until-shot LABEL (or --standard)')
    if a.after_file:
        suffix = a.name or 'after_%s_%d' % (a.after_file.replace('.', '_'), a.frames)
        print(cut(a.route, 'file', a.after_file, a.frames, suffix))
    else:
        suffix = a.name or 'until_%s' % a.until_shot
        print(cut(a.route, 'shot', a.until_shot, 0, suffix))
    return 0


if __name__ == '__main__':
    sys.exit(main())
