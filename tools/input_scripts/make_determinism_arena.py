"""Build determinism_arena.txt (Session 8 task 8a, fixed-seed check) from bench_lesnar_bryan.txt.

Usage: py tools/input_scripts/make_determinism_arena.py      (writes determinism_arena.txt next to this file)

The route boots with the frozen user data, picks Lesnar vs Bryan like the benchmark, and reaches the arena grid.
The grid opens on a randomly pre-selected arena. This script does NOT reset the cursor (no RB x3): it screenshots
the grid (captures/NNN_t8a_grid.bmp; the selected tile has a dark red frame instead of a white one) and quits.
Compare the selected tile across runs. Picking that arena to see its BG/BGnn.PAC load did not work (an A press
on the pre-selected tile is ignored, also after moving away and back). Run it with tools/bench/run_list.ps1
(needs the frozen user data). Example (in-process, from pwsh):
  & tools/bench/run_list.ps1 -Scripts @('../../../tools/input_scripts/determinism_arena.txt') -Extra '--wwe2k14_fixed_seed=1234'
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'bench_lesnar_bryan.txt')
OUT = os.path.join(HERE, 'determinism_arena.txt')

lines = open(SRC, encoding='utf-8').read().split('\n')
arena = next((i for i, l in enumerate(lines) if l.startswith('# Arena ')), None)
if arena is None:
    sys.exit(f'{SRC} has no "# Arena " line: the route cannot be cut at the arena grid. '
             'Update this generator to the new bench_lesnar_bryan.txt layout.')

# Header lines of the source route that describe the source, not this route.
DROP = ('# Benchmark route', '# entrance, 324', '# Generated by build_bench_routes.py')

head = [
    '# Fixed-seed check (Session 8 task 8a). Generated by make_determinism_arena.py from bench_lesnar_bryan.txt',
    '# (do not edit by hand). Boot -> Lesnar vs Bryan -> arena grid; screenshot the grid on its random',
    '# pre-selected arena (t8a_grid; dark red tile frame), quit. Needs the frozen user data (tools/bench/run_list.ps1).',
]
body = [l for l in lines[:arena] if not l.startswith(DROP)]
body = [l.replace('log bench: start lesnar_bryan', 'log t8a: start') for l in body]
grid = [
    '# Arena grid: no RB x3 reset, so the cursor stays on the pre-selected arena (dark red tile frame).',
    'wait_frames 90',
    'log t8a: arena grid',
    'screenshot t8a_grid',
    # Picking the pre-selected arena did not work: an A press on it is ignored (runs 211-213: 3 presses, no
    # MATCHHD.PAC), also after moving LEFT and back RIGHT (runs 215, 217-219: 5 presses). So stop at the grid.
    'wait_frames 60',
    'log t8a: done',
    'quit',
]
out = head + body + grid
with open(OUT, 'w', newline='\n') as f:
    f.write('\n'.join(out) + '\n')
print(f'{os.path.basename(OUT)}: {len(out)} lines')
