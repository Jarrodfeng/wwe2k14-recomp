def cmd_check(a, local):
    path = a.catalogue or default_out(local)
    try:
        head, ents = read_catalogue(path)
    except (OSError, ValueError) as ex:
        print('catalogue  ABSENT  %s (%s)\n  make it: py -I tools\\scene\\catalogue.py build' % (path, ex))
        return 1
    built = [h.split('\t')[1] for h in head if h.startswith('# built\t')]
    print('catalogue  %s  built %s  (%s ago), %d lines' % (path, built[0] if built else '?', age(time.time() - os.path.getmtime(path)), len(ents)))
    bad = 0
    for h in head:
        p = h.split('\t')
        if p[0] == '# kinds':
            print('kinds      ' + p[1])
        elif p[0] == '# source' and len(p) == 4:
            now = stamp(p[2]) or 'absent'
            state = 'same' if now == p[3] else ('ABSENT' if now == 'absent' else 'CHANGED')
            bad += state != 'same'
            mt = os.path.getmtime(p[2]) if os.path.exists(p[2]) else None
            print('source     %-8s %-46s age %-8s %s' % (state, p[1], age(time.time() - mt) if mt else '-', p[2]))
        elif p[0] == '# missing' and len(p) == 4:
            print('missing    %-26s %s%s' % (p[1], p[2], ('\n           make it: ' + p[3]) if p[3] else ''))
    if bad:
        print('STALE: %d source(s) changed since the build: py -I tools\\scene\\catalogue.py build' % bad)
        return 1
    print('fresh (a missing part is a known gap, not staleness)')
    return 0


