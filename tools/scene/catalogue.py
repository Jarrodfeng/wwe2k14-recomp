class Build:
    def __init__(self, data, local, game, menu_log=None):
        self.data, self.local, self.game, self.menu_log = data, local, game, menu_log
        self.sources = []    # (name, path)
        self.missing = []    # (section, why, command)
        self.entries = []

    def src(self, name, path):
        if (name, path) not in self.sources:
            self.sources.append((name, path))

    def miss(self, section, why, command=''):
        self.missing.append((section, why, command))

    def add(self, kind, id_, name, aliases, where):
        self.entries.append(Entry(kind, str(id_), name, [a for a in aliases if a and clean(a).lower() != clean(name).lower()], where))

    # db\ids: committed, our annotations
    def ids(self, fname):
        p = os.path.join(self.data, 'db', 'ids', fname)
        self.src('db/ids/' + fname, p)
        with open(p, encoding='utf-8') as f:
            return json.load(f).get('entries', [])

    def characters(self):
        for e in self.ids('characters.json'):
            if not isinstance(e.get('id'), int) or not e.get('name'):
                continue
