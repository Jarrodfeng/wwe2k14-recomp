def clean(s):
    return re.sub(r'\s+', ' ', str(s)).strip()


def line_of(e):
    return '\t'.join((e.kind, clean(e.id), clean(e.name), ' | '.join(clean(a).replace('|', '/') for a in e.aliases if clean(a)), clean(e.where)))


def read_catalogue(path):
    """-> (header lines, [Entry]). Raises OSError when absent, ValueError on a line that is not 5 fields."""
    head, ents = [], []
    with open(path, encoding='utf-8') as f:
        for n, ln in enumerate(f, 1):
            ln = ln.rstrip('\n')
            if not ln:
                continue
            if ln.startswith('#'):
                head.append(ln)
                continue
            p = ln.split('\t')
            if len(p) != 5:
                raise ValueError('%s:%d: %d fields, not 5' % (path, n, len(p)))
            ents.append(Entry(p[0], p[1], p[2], [a for a in p[3].split(' | ') if a], p[4]))
    return head, ents


def stamp(path):
    """sha256 (16 hex) of a file up to 16 MB, else size + mtime; None when absent."""
    try:
        st = os.stat(path)
    except OSError:
        return None
    if st.st_size > (16 << 20):
        return 'size%d-mtime%d' % (st.st_size, int(st.st_mtime))
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        h.update(f.read())
    return h.hexdigest()[:16]


def age(seconds):
    s = max(0, int(seconds))
    if s < 3600:
        return '%dm' % (s // 60)
    if s < 172800:
        return '%dh%02dm' % (s // 3600, s % 3600 // 60)
    return '%dd' % (s // 86400)


def read_text(p):
    with open(p, encoding='utf-8', errors='replace') as f:
        return f.read()


