# ------------------------------------------------------------------------------------------------ folding and ranking
def fold(text):
    """Lower case, diacritics dropped, every run of non-letters / digits one space: the tokens."""
    s = unicodedata.normalize('NFKD', str(text))
    s = ''.join(c for c in s if not unicodedata.combining(c)).lower()
    return re.findall(r'[a-z0-9]+', s)


def roman(w):
    """A roman numeral 2-39 of two letters or more ('xxix' -> 29), else None (single letters stay words)."""
    if len(w) < 2 or not ROMAN_RX.match(w):
        return None
    v = {'i': 1, 'v': 5, 'x': 10}
    return sum(v[c] if i + 1 == len(w) or v[c] >= v[w[i + 1]] else -v[c] for i, c in enumerate(w))


def osa(a, b):
    """Edit distance with adjacent transpositions (optimal string alignment): 'brayn' -> 'bryan' is 1."""
    d = [[0] * (len(b) + 1) for _ in range(len(a) + 1)]
    for i in range(len(a) + 1):
        d[i][0] = i
    for j in range(len(b) + 1):
        d[0][j] = j
    for i in range(1, len(a) + 1):
        for j in range(1, len(b) + 1):
            c = 0 if a[i - 1] == b[j - 1] else 1
            d[i][j] = min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + c)
            if i > 1 and j > 1 and a[i - 1] == b[j - 2] and a[i - 2] == b[j - 1]:
                d[i][j] = min(d[i][j], d[i - 2][j - 2] + 1)
    return d[len(a)][len(b)]


def token_sim(q, t):
    if q == t:
        return 1.0
    if any(c.isdigit() for c in q + t):
        return 0.0   # numbers match exactly or not at all (29 is not 28)
    if len(q) >= 3 and t.startswith(q):
        return 0.9
    if len(q) < 4:
        return 0.0
    s = 1.0 - osa(q, t) / max(len(q), len(t))
    return s if s >= 0.6 else 0.0


def text_score(qt, tt):
    """Token overlap with edit distance: the mean of each query token's best match, less 0.03 per name token left unmatched
    (so the shorter name wins a tie); the whole text equal scores 1.1."""
    if not qt or not tt:
        return 0.0
    if qt == tt:
        return 1.1
    used, total = set(), 0.0
    for q in qt:
        best, at = 0.0, None
        for i, t in enumerate(tt):
            s = token_sim(q, t)
            if s > best:
                best, at = s, i
        total += best
        if at is not None:
            used.add(at)
    return total / len(qt) - min(0.3, 0.03 * (len(tt) - len(used)))


def entry_score(e, qvars, raw):
    rid = raw.strip().lstrip('#').lower()
    if rid and rid == str(e.id).lower():
        return 1.2   # the id itself ("#324", "76", "pin")
    texts = [fold(e.name)] + [fold(a) for a in e.aliases]
    return max(text_score(qt, tt) for qt in qvars for tt in texts)


def _idkey(i):
    s = str(i)
    return (0, int(s), '') if s.lstrip('-').isdigit() else (1, 0, s)


def rank(entries, words, kinds=None, n=5):
    """-> (ok, [(score, Entry)]). ok: the hits (score >= GOOD and within NEAR of the best), best first, at most n.
    not ok: the n nearest (score, then the whole-string likeness), whatever their score."""
    raw = ' '.join(words) if isinstance(words, (list, tuple)) else str(words)
    qt = fold(raw)
    alt = [str(roman(t)) if roman(t) else t for t in qt]   # "wrestlemania xxix" also asks "wrestlemania 29"
    qvars = [qt] if alt == qt else [qt, alt]
    pool = [e for e in entries if not kinds or e.kind in kinds]
    order = {k: i for i, k in enumerate(KINDS)}
    scored = sorted(((entry_score(e, qvars, raw), e) for e in pool),
                    key=lambda se: (-se[0], order.get(se[1].kind, 99), _idkey(se[1].id)))
    if scored and scored[0][0] >= GOOD:
        best = scored[0][0]
        return True, [se for se in scored if se[0] >= GOOD and se[0] >= best - NEAR][:n]
    q = ' '.join(qt)
    near = sorted(scored, key=lambda se: (-round(se[0], 6), -difflib.SequenceMatcher(None, q, ' '.join(fold(se[1].name))).ratio()))
    return False, near[:n]


def kinds_of(spec):
    """--kind K[,K]: exact names or unique prefixes of KINDS (SCENETOOL's --in SECTION is the same)."""
    if not spec:
        return None
    out = []
    for k in spec.split(','):
        k = k.strip().lower()
        hit = [x for x in KINDS if x == k] or [x for x in KINDS if x.startswith(k)]
        if len(hit) != 1:
            raise SystemExit('--kind %s: one of %s' % (k, ', '.join(KINDS)))
        out.append(hit[0])
    return out


