def stale(path):
    """[reasons] the catalogue at `path` is stale or absent ([] = fresh)."""
    try:
        head, _ = read_catalogue(path)
    except (OSError, ValueError) as ex:
        return ['catalogue unreadable: %s' % ex]
    why = []
    for h in head:
        p = h.split('\t')
        if p[0] == '# source' and len(p) == 4 and (stamp(p[2]) or 'absent') != p[3]:
            why.append('%s changed (%s)' % (p[1], p[2]))
    return why


