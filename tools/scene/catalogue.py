    # `--wwe2k14_menu_goto_list` listing (src\menu_goto.h:72-88), kept as numbers in out\scene\front_end_records.json
    def front_end(self):
        ap = os.path.join(self.data, 'docs', 'systems', 'game_atlas.json')
        self.src('docs/systems/game_atlas.json', ap)
        with open(ap, encoding='utf-8') as f:
            atlas = json.load(f)
        labels, opened, leads = {}, {}, {}
        for key, node in atlas.get('nodes', {}).items():
            if node.get('kind') == 'list' and key.startswith('list:'):
                m = int(key[5:])
                for i, lab in enumerate(node.get('labels') or []):
                    labels[(m, i)] = lab
                if node.get('opened_from'):
                    opened[m] = (node['opened_from'].get('menu'), node['opened_from'].get('item'))
        for e in atlas.get('edges', []):
            if e.get('from', '').startswith('list:') and 'item' in e.get('how', {}):
                leads[(int(e['from'][5:]), e['how']['item'])] = e.get('to')

        def path(m, i, depth=0):
            here = labels.get((m, i), 'menu %d item %d' % (m, i))
            up = opened.get(m)
            if up and up[0] not in (None, 0) and depth < 12:
                return path(up[0], up[1], depth + 1) + ' > ' + here
            return here

        recs = self.listing()
        if recs is None:
            for (m, i), lab in sorted(labels.items()):
                self.add('menu', 'm%d.%d' % (m, i), path(m, i), [lab],
                         'scene menu // at page=? (record id unknown: no menu listing read) -> %s' % leads.get((m, i), '?'))
            return
        for r in recs:
            rid, m, i, code, parent, enter = r['record'], r['menu'], r['stock_item'], r['code'], r['parent'], r['enterable']
