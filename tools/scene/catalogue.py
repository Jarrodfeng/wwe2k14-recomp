    def run(self):
        for step in (self.characters, self.arenas, self.types, self.front_end, self.cas, self.wm30, self.stages, self.vocabulary, self.modes):
            step()
        self.miss('wrestler (imported pack)', "the importer's pack superstars (seat 397 ...): no source read yet (SCENETOOL 2.4, lane 3)", '')
        self.number_twins()
