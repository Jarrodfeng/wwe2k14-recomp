#!/usr/bin/env python3
"""Generates src\\renderer_scene\\fx_tables.h: for every variant of the effect registry (src\\renderer\\shaders\\spv\\fx_registry.h), the
vertex inputs its shader declares (location, name, components) and the named constants of its uniform block (name, byte offset, vec4
count). The scene front-end (src\\renderer_scene\\) binds materials by NAME with these: the registry only knows registers.
Our own metadata only (names and offsets); no game data. Run again after tools\\renderer\\compile_shaders.py changed an effect.

  py -I tools\\scene\\gen_fx_tables.py [--check]     (--check: exit 1 if the committed header is out of date)
"""
import glob
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
SOURCE = os.path.join(ROOT, 'src', 'renderer', 'shaders')
FX = os.path.join(SOURCE, 'fx')
OUT = os.path.join(ROOT, 'src', 'renderer_scene', 'fx_tables.h')
SDK_ROOT = r'C:\VulkanSDK'
SDK = os.path.join(SDK_ROOT, sorted(os.listdir(SDK_ROOT))[-1], 'Bin')

INTERP = r'layout\s*\(\s*location\s*=\s*(\d+)\s*\)\s*(?:flat\s+|smooth\s+|noperspective\s+)?%s\s+(?:float|vec[234])\s+(\w+)\s*;'
IN_DECL = re.compile(r'layout\s*\(\s*location\s*=\s*(\d+)\s*\)\s*in\s+(float|vec[234])\s+(\w+)\s*;')


def preprocess(path, stage, defines):
    done = subprocess.run([os.path.join(SDK, 'glslangValidator.exe'), '-E', '-S', stage, '-I' + SOURCE, '-I' + FX,
                           *[f'-D{d}' for d in defines], path], capture_output=True, text=True)
    if done.returncode != 0:
        raise RuntimeError(f'preprocess failed {path}:\n{done.stdout}{done.stderr}')
    return done.stdout


def block_members(text, block):
    match = re.search(block + r'\s*\{(.*?)\}', text, re.S)
    out, size = [], 0
    if match:
        for kind, name, count in re.findall(r'(u?vec4)\s+(\w+)\s*(?:\[\s*(\d+)\s*\])?\s*;', match.group(1)):
            n = int(count) if count else 1
            out.append((name, size, n))
            size += 16 * n
    return out


def main():
    rows = []  # (variant ident, inputs, fields)
    for json_path in sorted(glob.glob(os.path.join(FX, '*.fx.json'))):
        with open(json_path, encoding='utf-8') as f:
            spec = json.load(f)
        effect = spec['effect']
        for stage_key, ext, stage, block in (('vertex', '.vert', 'vert', 'VertexConstants'), ('fragment', '.frag', 'frag', 'FragmentConstants')):
            variants = list(spec.get(stage_key, []))
            if effect.startswith('yCh_') and stage_key == 'vertex':
                variants += [{**v, 'name': v['name'] + '_velocity', 'defines': list(v.get('defines', [])) + ['VELOCITY']} for v in spec.get('vertex', [])]
            for v in variants:
                path = os.path.join(FX, v.get('source', effect) + ext)
                text = preprocess(path, stage, v.get('defines', []))
                inputs = []
                if stage_key == 'vertex':
                    inputs = [(int(l), {'float': 1, 'vec2': 2, 'vec3': 3, 'vec4': 4}[k], n) for l, k, n in IN_DECL.findall(text)]
                    inputs.sort()
                # Interpolators (a vertex variant's outputs / a fragment variant's inputs): the pairing check needs them.
                pattern = re.compile(INTERP % ('out' if stage_key == 'vertex' else 'in'))
                interps = sorted((int(l), re.sub(r'^(in|out)', '', n)) for l, n in pattern.findall(text))
                fields = block_members(text, block)
                rows.append((f'{effect}_{v["name"]}_{stage_key}', inputs, fields, interps, list(v.get('defines', []))))
    rows.sort(key=lambda r: r[0])
    out = ['// Generated by tools\\scene\\gen_fx_tables.py from the effect sources. Names and offsets only; do not edit.',
           '#pragma once', '#include <cstdint>', '', 'namespace rdr_scene::fxt {',
           'struct Input { uint8_t location, components; const char* name; };',
           'struct Field { const char* name; uint16_t offset, vec4s; };',
           'struct Interp { uint8_t location; const char* name; };',
           'struct VariantTable { const char* variant; const Input* inputs; uint8_t input_count; const Field* fields; uint8_t field_count;'
           ' const Interp* interps; uint8_t interp_count; const char* defines; };', '']
    table = []
    for i, (ident, inputs, fields, interps, defines) in enumerate(rows):
        if interps:
            out.append(f'inline constexpr Interp kP{i}[] = {{' + ', '.join(f'{{{l}, "{n}"}}' for l, n in interps) + '};')
        if inputs:
            out.append(f'inline constexpr Input kI{i}[] = {{' + ', '.join(f'{{{l}, {c}, "{n}"}}' for l, c, n in inputs) + '};')
        if fields:
            out.append(f'inline constexpr Field kF{i}[] = {{' + ', '.join(f'{{"{n}", {o}, {c}}}' for n, o, c in fields) + '};')
        table.append(f'{{"{ident}", {f"kI{i}" if inputs else "nullptr"}, {len(inputs)}, {f"kF{i}" if fields else "nullptr"}, {len(fields)}, '
                     f'{f"kP{i}" if interps else "nullptr"}, {len(interps)}, "{" ".join(defines)}"}}')
    out.append('inline constexpr VariantTable kTables[] = {\n  ' + ',\n  '.join(table) + '\n};')
    out.append('}  // namespace rdr_scene::fxt\n')
    text = '\n'.join(out)
    if '--check' in sys.argv:
        with open(OUT, encoding='utf-8') as f:
            return 0 if f.read().replace('\r\n', '\n') == text else 1  # (git may check the file out with CRLF)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', newline='\n', encoding='utf-8') as f:
        f.write(text)
    print(f'{len(rows)} variants -> {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
