"""Session 94 (gpu_d3d_decouple, phase 1A): build the MULTIVIEW variants of our own vertex shaders.

Same idea as build_instanced_vs.py (the plain .vert / .glsl sources and their headers are never touched; a temp copy is rewritten and compiled):
  - every  fc.c[EXPR]  (in the .vert and in the .glsl includes) becomes  fc.c[(EXPR) + XE_V],  XE_V = gl_ViewIndex * XE_VSTRIDE
  - the constants block is widened to 512 vec4 = 2 views x the 256-vec4 block the SDK's translated shaders use with gpu_d3d_decouple bit 3
    (the dynamic-offset descriptor's whole range; phase 1B's data layout)
  - XE_VSTRIDE = a specialization constant (SpecId 1, int, default 0): the vec4s between two views' constant blocks. With 0 every view reads the
    same constants (the A/A mode); the SDK patches it to 256 when views get their own blocks.
  - GL_EXT_multiview (OpCapability MultiView): these modules are only valid in a render pass with a view mask, so they are a separate
    variant set the SDK picks while gpu_d3d_decouple is on. The plain shaders keep their SPIR-V byte for byte.
Output: <out>\\<name>_mv_vert.h (array <name>_mv_vert_spv).

    py tools\\shaders\\build_multiview_vs.py [--out DIR] [name ...]
"""
import os, re, shutil, subprocess, sys, tempfile, glob

R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.environ.get('XE_SCENE_SRC', os.path.join(R, 'src', 'scene'))


def find_glslang():
    c = sorted(glob.glob(r'C:\VulkanSDK\*\Bin\glslangValidator.exe'), reverse=True)
    if c:
        return c[0]
    p = shutil.which('glslangValidator')
    if p:
        return p
    raise SystemExit('glslangValidator not found (Vulkan SDK)')


def rewrite_fc(text):
    """fc.c[EXPR] -> fc.c[(EXPR) + XE_V], with the matching bracket found by nesting. Returns (text, count)."""
    out, i, n = [], 0, 0
    key = 'fc.c['
    while True:
        j = text.find(key, i)
        if j < 0:
            out.append(text[i:])
            break
        out.append(text[i:j + len(key)])
        k, depth = j + len(key), 1
        while depth:
            ch = text[k]
            depth += (ch == '[') - (ch == ']')
            k += 1
        expr = text[j + len(key):k - 1]
        out.append('(' + expr + ') + XE_V]')
        i = k
        n += 1
    return ''.join(out), n


def main():
    args = sys.argv[1:]
    out_dir = os.path.join(SRC, 'spirv')
    if args[:1] == ['--out']:
        out_dir, args = args[1], args[2:]
    os.makedirs(out_dir, exist_ok=True)
    glslang = find_glslang()
    tmp = tempfile.mkdtemp(prefix='s94mv_')
    made = skipped = 0
    try:
        for g in glob.glob(os.path.join(SRC, '*.glsl')):
            text = open(g, encoding='utf-8').read()
            if 'fc.c[' in text:
                text, _ = rewrite_fc(text)
            text = re.sub(r'vec4 c\[\d+\]', 'vec4 c[512]', text)
            open(os.path.join(tmp, os.path.basename(g)), 'w', encoding='utf-8', newline='\n').write(text)
        for f in sorted(glob.glob(os.path.join(SRC, '*.vert'))):
            base = os.path.splitext(os.path.basename(f))[0]
            if args and base not in args:
                continue
            text = open(f, encoding='utf-8').read()
            inc = '#include "xenos_vs.glsl"'
            if text.count(inc) != 1:
                continue
            text, n1 = rewrite_fc(text)
            text, n2 = re.subn(r'vec4 c\[\d+\]', 'vec4 c[512]', text)
            # the .glsl includes that declare the block themselves are widened in the temp copies below
            m = re.match(r'(#version[^\n]*\n)', text)
            assert m, base
            text = m.group(1) + '#extension GL_EXT_multiview : require\n' + text[m.end():]
            text = text.replace(inc, inc + '\n// Session 94 (gpu_d3d_decouple): the multiview variant (tools/shaders/build_multiview_vs.py)\n'
                                'layout(constant_id = 1) const int XE_VSTRIDE = 0;\n#define XE_V (gl_ViewIndex * XE_VSTRIDE)\n')
            tf = os.path.join(tmp, base + '.vert')
            open(tf, 'w', encoding='utf-8', newline='\n').write(text)
            spv = os.path.join(tmp, base + '.spv')
            r = subprocess.run([glslang, '-V', '--target-env', 'vulkan1.1', '-S', 'vert', '-o', spv, tf], capture_output=True, text=True)
            if r.returncode:
                print('SKIP %s: %s' % (base, (r.stdout + r.stderr).strip().splitlines()[-3:]))
                skipped += 1
                continue
            data = open(spv, 'rb').read()
            words = ['0x%08X' % int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
            ident = base + '_mv_vert'
            lines = ['    ' + ', '.join(words[i:i + 8]) + ',' for i in range(0, len(words), 8)]
            header = ['#pragma once',
                      '// Session 94: the multiview variant of ../%s.vert, generated by tools\\shaders\\build_multiview_vs.py (every float constant read at' % base,
                      '// register + gl_ViewIndex * XE_VSTRIDE; XE_VSTRIDE = specialization constant 1, default 0). Do not edit: edit the .vert and run the script.',
                      '#include <cstdint>', '', 'inline constexpr uint32_t %s_spv[] = {' % ident] + lines + ['};', '']
            open(os.path.join(out_dir, ident + '.h'), 'w', encoding='utf-8', newline='').write('\r\n'.join(header))
            print('%s: %d fc refs -> %s.h (%d words)' % (base, n1, ident, len(words)))
            made += 1
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print('made %d, skipped %d' % (made, skipped))


main()
