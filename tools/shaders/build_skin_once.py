"""Session 95 (gpu_native_skin_once): build the skin-once shaders into src\\scene\\spirv:
  skin_once_comp.h               src\\scene\\skin_once.comp, the one compute shader that skins a frame's wrestler vertices
  vs_skin_shadow_so_vert.h, vs_skin_rim_so_vert.h   the side passes' variants (position only, every vertex layout)
  <name>_so_vert.h               for each wrestler main-pass shader vs_ch_*.vert: the same source with XE_SKIN_ONCE (the skinned rows come from vertex inputs, the blend is skipped)
Answers: "I changed a vs_ch shader or skin_once.comp: remake the skin-once headers." The plain shaders and their headers are not touched.

    py tools\\shaders\\build_skin_once.py [--out DIR]
"""
import glob, os, re, shutil, subprocess, sys, tempfile

R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(R, 'src', 'scene')
# The main-pass shaders and the dwords of their raw values in their own layout: (texture coordinate, colour; -2 = none).
MAIN = {
    'vs_ch_gear_w12': (11, 10), 'vs_ch_gear_w9': (8, 7), 'vs_ch_skin_a': (11, 10), 'vs_ch_skin_fx': (11, 10), 'vs_ch_skin_lean': (8, 7),
    'vs_ch_anisotropic': (11, 10), 'vs_ch_reflect_w12': (11, 10), 'vs_ch_reflect_w11': (10, -2), 'vs_ch_reflect_w9': (8, 7), 'vs_ch_reflect_w9p': (8, 7),
}
SIDE = ['vs_skin_shadow_so', 'vs_skin_rim_so']


def find_glslang():
    c = sorted(glob.glob(r'C:\VulkanSDK\*\Bin\glslangValidator.exe'), reverse=True)
    if c:
        return c[0]
    p = shutil.which('glslangValidator')
    if p:
        return p
    raise SystemExit('glslangValidator not found (Vulkan SDK)')


def header(out, ident, spv, note):
    data = open(spv, 'rb').read()
    words = ['0x%08X' % int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
    lines = ['    ' + ', '.join(words[i:i + 8]) + ',' for i in range(0, len(words), 8)]
    text = ['#pragma once', '// Session 95: %s, generated by tools\\shaders\\build_skin_once.py. Do not edit: edit the source and run the script.' % note,
            '#include <cstdint>', '', 'inline constexpr uint32_t %s_spv[] = {' % ident] + lines + ['};', '']
    open(os.path.join(out, ident + '.h'), 'w', encoding='utf-8', newline='').write('\r\n'.join(text))
    print('%s.h: %d words' % (ident, len(words)))


def main():
    args = sys.argv[1:]
    out = os.path.join(SRC, 'spirv')
    if '--out' in args:
        out = args[args.index('--out') + 1]
    glslang = find_glslang()
    os.makedirs(out, exist_ok=True)
    tmp = tempfile.mkdtemp(prefix='s95so_')
    try:
        for g in glob.glob(os.path.join(SRC, '*.glsl')):
            shutil.copy(g, tmp)

        def compile_(path, stage, spv):
            r = subprocess.run([glslang, '-V', '--target-env', 'vulkan1.0', '-S', stage, '-o', spv, path], capture_output=True, text=True)
            if r.returncode:
                print(r.stdout, r.stderr)
                raise SystemExit('glslangValidator failed on ' + path)

        spv = os.path.join(tmp, 'o.spv')
        shutil.copy(os.path.join(SRC, 'skin_once.comp'), tmp)
        compile_(os.path.join(tmp, 'skin_once.comp'), 'comp', spv)
        header(out, 'skin_once_comp', spv, 'src\\scene\\skin_once.comp')
        for base in SIDE:
            shutil.copy(os.path.join(SRC, base + '.vert'), tmp)
            compile_(os.path.join(tmp, base + '.vert'), 'vert', spv)
            header(out, base + '_vert', spv, 'src\\scene\\%s.vert' % base)
        for base, (uv, quad) in MAIN.items():
            text = open(os.path.join(SRC, base + '.vert'), encoding='utf-8').read()
            inc = '#include "xenos_vs.glsl"'
            assert text.count(inc) == 1, base
            text = text.replace(inc, '#define XE_SKIN_ONCE\n#define XE_SO_UV %d\n#define XE_SO_QUAD %d\n' % (uv, quad) + inc)
            tf = os.path.join(tmp, base + '.vert')
            open(tf, 'w', encoding='utf-8', newline='\n').write(text)
            compile_(tf, 'vert', spv)
            header(out, base + '_so_vert', spv, 'the skin-once variant of ../%s.vert' % base)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == '__main__':
    main()
