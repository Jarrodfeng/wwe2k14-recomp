"""Session 98 (Arena Viewer phone port, stage B): the Vulkan SPIR-V of the viewer's shaders, from the SAME HLSL the D3D11 backend
compiles at run time (src\\assets\\view\\viewer_hlsl.h). Each entry point is compiled with DXC (-spirv, Vulkan 1.1) into
src\\assets\\view\\spirv\\viewer_spv.h (one uint32_t array per entry, plus a lookup table). Our own shaders: committed (CLAUDE.md rule 1).

Bindings: the scene source carries explicit [[vk::binding(b, set)]] / [[vk::location]] behind __spirv__ (set 0 per pass, set 1 per
draw); the small shaders (post, blur, flash, sprite, composite) take register shifts: b -> 0+, t -> 1+, s -> 8+ (set 0).
SV_Position.w in pixel shaders follows D3D (-fvk-use-dx-position-w); HLSL 2018 rules (-HV 2018: FXC's vector ?: select). The clip-space Y flip is the renderer's (negative-height viewport).

    py tools\\shaders\\build_viewer_spv.py            (rebuild the header)
    py tools\\shaders\\build_viewer_spv.py --check    (exit 1 when the header is out of date)
"""
import glob, os, re, shutil, subprocess, sys, tempfile

R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(R, 'src', 'assets', 'view', 'viewer_hlsl.h')
OUT = os.path.join(R, 'src', 'assets', 'view', 'spirv', 'viewer_spv.h')


def find_dxc():
    env = os.environ.get('VULKAN_SDK')
    cands = ([os.path.join(env, 'Bin', 'dxc.exe')] if env else []) + sorted(glob.glob(r'C:\VulkanSDK\*\Bin\dxc.exe'), reverse=True)
    for c in cands:
        if os.path.isfile(c):
            return c
    p = shutil.which('dxc')
    if p:
        return p
    raise SystemExit('dxc not found (Vulkan SDK)')


def sources():
    text = open(SRC, encoding='utf-8').read()
    parts = dict(re.findall(r'inline const char\* const (k\w+) = R"HLSL\((.*?)\)HLSL";', text, re.S))
    scene = parts['kScene']
    assert scene.count('//SHADOW_CHUNK') == 1
    parts['scene'] = scene.replace('//SHADOW_CHUNK', parts['kShadow'] + parts['kPick'], 1)  # = hlsl::SceneSource()
    return parts


SMALL = ['-fvk-b-shift', '0', '0', '-fvk-t-shift', '1', '0', '-fvk-s-shift', '8', '0', '-fvk-u-shift', '16', '0']
# (source, entry, stage, shifts?)
ENTRIES = [('scene', e, s, False) for e, s in [('vs', 'vs'), ('ps', 'ps'), ('ps_caster', 'ps'), ('ps_rim', 'ps'), ('ps_plane', 'ps'),
                                                ('vs_plane', 'vs'), ('vs_id', 'vs'), ('vs_mask', 'vs'), ('ps_id', 'ps'), ('ps_mask', 'ps')]] + \
          [('kFlash', 'vs_flash', 'vs', True), ('kFlash', 'ps_flash', 'ps', True), ('kSprite', 'vs_sprite', 'vs', True),
           ('kSprite', 'ps_sprite', 'ps', True), ('kBlur', 'vsFull', 'vs', True), ('kBlur', 'psDown', 'ps', True),
           ('kBlur', 'psBlur', 'ps', True), ('kBlur', 'psRim13', 'ps', True), ('kPost', 'vsFull', 'vs', True)] + \
          [('kPost', e, 'ps', True) for e in ('psDownNear', 'psDownFar', 'psBlur13', 'psBright', 'psBlur15', 'psGlare', 'psCombine')] + \
          [('kComp', 'vs_fs', 'vs', True), ('kComp', 'ps_comp', 'ps', True)]


def build():
    dxc = find_dxc()
    parts = sources()
    tmp = tempfile.mkdtemp(prefix='viewer_spv_')
    out = ['#pragma once',
           '// Session 98 (Arena Viewer phone port): SPIR-V of src\\assets\\view\\viewer_hlsl.h for the Vulkan backend, generated by',
           '// tools\\shaders\\build_viewer_spv.py (DXC -spirv). Do not edit: edit viewer_hlsl.h and run the script. Our own shaders.',
           '#include <cstddef>', '#include <cstdint>', '#include <cstring>', '', 'namespace view {', 'namespace spv {', '']
    table = []
    try:
        for src, entry, stage, small in ENTRIES:
            f = os.path.join(tmp, src + '.hlsl')
            if not os.path.exists(f):
                open(f, 'w', encoding='utf-8', newline='\n').write(parts[src])
            spv = os.path.join(tmp, f'{src}_{entry}.spv')
            args = [dxc, '-spirv', '-fspv-target-env=vulkan1.1', '-fvk-use-dx-position-w', '-Zpr', '-O3', '-HV', '2018', '-T', stage + '_6_0', '-E', entry,
                    '-Fo', spv] + (SMALL if small else []) + [f]
            r = subprocess.run(args, capture_output=True, text=True)
            if r.returncode:
                print(r.stdout, r.stderr)
                raise SystemExit(f'dxc failed on {src}:{entry}')
            data = open(spv, 'rb').read()
            words = ['0x%08X' % int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
            ident = f'{"scene" if src == "scene" else src[1:].lower()}_{entry}'
            out.append(f'inline constexpr uint32_t k_{ident}[] = {{')
            out += ['    ' + ', '.join(words[i:i + 8]) + ',' for i in range(0, len(words), 8)]
            out += ['};', '']
            table.append((f'{"scene" if src == "scene" else src[1:].lower()}', entry, f'k_{ident}'))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    out += ['struct Entry { const char* source; const char* entry; const uint32_t* code; size_t bytes; };',
            'inline constexpr Entry kEntries[] = {']
    out += [f'    {{"{s}", "{e}", {k}, sizeof({k})}},' for s, e, k in table]
    out += ['};', '',
            '// The SPIR-V of `entry` in `source` ("scene", "flash", "sprite", "blur", "post", "comp"); null when there is none.',
            'inline const Entry* Find(const char* source, const char* entry) {',
            '  for (const Entry& e : kEntries)',
            '    if (!std::strcmp(e.source, source) && !std::strcmp(e.entry, entry)) return &e;',
            '  return nullptr;',
            '}', '', '}  // namespace spv', '}  // namespace view', '']
    return '\r\n'.join(out)


def main():
    text = build()
    if '--check' in sys.argv:
        cur = open(OUT, encoding='utf-8', newline='').read() if os.path.exists(OUT) else ''
        if cur != text:
            print('viewer_spv.h is out of date: run py tools\\shaders\\build_viewer_spv.py')
            return 1
        print('viewer_spv.h is up to date')
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='utf-8', newline='').write(text)
    print(f'wrote {OUT} ({len(ENTRIES)} entries)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
