"""The one writer of our own SPIR-V arrays (S110 SPIRVDATA; the S105 pattern of src\\renderer\\shaders\\spv, applied to src\\scene\\spirv and src\\post\\spirv).

Every generator (tools\\post\\build_shaders.ps1, tools\\shaders\\build_*.py) writes through this module, so a header holds only
    extern const uint32_t NAME[COUNT];          (the count stays a compile-time constant: std::size / sizeof users keep working)
and the words live in a sibling <stem>_data.inc that ONE data unit per shard includes:
    <dir>\\scene_spirv_data_<k>.cpp   (4 shards, src\\scene\\spirv)      <dir>\\post_spirv_data.cpp   (1 shard, src\\post\\spirv)
Nothing but those units parses the words: the game's main.cpp no longer carries 40 MB of array text on every compile.

    py -I tools\\shaders\\spv_emit.py --refresh DIR     rewrite the data units of DIR from the *_data.inc files that sit next to a header
    py -I tools\\shaders\\spv_emit.py --selftest        the planted checks (a header holding words, a stale unit, a one-word change)
"""
import os, re, sys, zlib

SHARDS = {'scene': 4, 'post': 1}


def dir_kind(out_dir):
    return 'post' if os.path.basename(os.path.dirname(os.path.abspath(out_dir))) == 'post' else 'scene'


def header_text(comment_lines, ident, count):
    return '\r\n'.join(['#pragma once'] + list(comment_lines) + ['#include <cstdint>', '', 'extern const uint32_t %s[%d];' % (ident, count), ''])


def inc_text(ident, words):
    lines = ['    ' + ', '.join(words[i:i + 8]) + ',' for i in range(0, len(words), 8)]
    return '\r\n'.join(['const uint32_t %s[%d] = {' % (ident, len(words))] + lines + ['};', ''])


def write(out_dir, stem, comment_lines, ident, words):
    """words: list of '0x%08X' strings. Writes <stem>.h and <stem>_data.inc (no data unit: call refresh_units once per run)."""
    open(os.path.join(out_dir, stem + '.h'), 'w', encoding='utf-8', newline='').write(header_text(comment_lines, ident, len(words)))
    open(os.path.join(out_dir, stem + '_data.inc'), 'w', encoding='utf-8', newline='').write(inc_text(ident, words))


def inc_path(header_path):
    return os.path.splitext(header_path)[0] + '_data.inc'


def read_words(header_path):
    """The words of the array of a header (read from its data .inc)."""
    text = open(inc_path(header_path), encoding='utf-8').read()
    return [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]{8}', text[text.index('= {'):])]


def shard_of(stem, n):
    return zlib.crc32(stem.encode()) % n


def unit_names(out_dir):
    kind = dir_kind(out_dir)
    n = SHARDS[kind]
    return ['post_spirv_data.cpp'] if kind == 'post' else ['scene_spirv_data_%d.cpp' % k for k in range(n)]


def unit_texts(out_dir):
    kind = dir_kind(out_dir)
    n = SHARDS[kind]
    stems = sorted(f[:-len('_data.inc')] for f in os.listdir(out_dir) if f.endswith('_data.inc') and os.path.exists(os.path.join(out_dir, f[:-len('_data.inc')] + '.h')))
    names = unit_names(out_dir)
    body = [[] for _ in range(n)]
    for s in stems:
        body[shard_of(s, n)] += ['#include "%s.h"' % s, '#include "%s_data.inc"' % s]
    texts = {}
    for k, name in enumerate(names):
        head = ['// Generated by tools\\shaders\\spv_emit.py (S110 SPIRVDATA). Our own SPIR-V words: the only unit that parses them (the headers only declare the arrays).',
                '// Shard %d of %d. Do not edit: edit the shader source and run its generator.' % (k, n), '#include <cstdint>', '']
        texts[name] = '\r\n'.join(head + body[k] + [''])
    return texts


def refresh_units(out_dir):
    for name, text in unit_texts(out_dir).items():
        p = os.path.join(out_dir, name)
        old = open(p, encoding='utf-8', newline='').read() if os.path.exists(p) else None
        if old != text:
            open(p, 'w', encoding='utf-8', newline='').write(text)
    return list(unit_names(out_dir))


def selftest():
    import tempfile
    bad = 0
    with tempfile.TemporaryDirectory() as t:
        d = os.path.join(t, 'scene', 'spirv')
        os.makedirs(d)
        ws = ['0x%08X' % i for i in (0x07230203, 1, 2, 3, 4, 5, 6, 7, 8, 9)]
        write(d, 'a_x', ['// c'], 'a_x_spv', ws)
        refresh_units(d)
        h = open(os.path.join(d, 'a_x.h')).read()
        ok = 'extern const uint32_t a_x_spv[10];' in h and '0x0000' not in h
        print('selftest header declares only:', 'PASS' if ok else 'FAIL'); bad += not ok
        ok = read_words(os.path.join(d, 'a_x.h')) == [int(w, 16) for w in ws]
        print('selftest words round-trip:', 'PASS' if ok else 'FAIL'); bad += not ok
        cpp = ''.join(open(os.path.join(d, n)).read() for n in unit_names(d))
        ok = '#include "a_x_data.inc"' in cpp
        print('selftest data unit includes the inc:', 'PASS' if ok else 'FAIL'); bad += not ok
    return bad


if __name__ == '__main__':
    if '--selftest' in sys.argv:
        sys.exit(1 if selftest() else 0)
    if '--refresh' in sys.argv:
        for n in refresh_units(sys.argv[sys.argv.index('--refresh') + 1]):
            print('data unit', n)
        sys.exit(0)
    print(__doc__)
    sys.exit(2)
