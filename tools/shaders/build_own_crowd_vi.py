"""Session 95 (P7 of out\\s95\\android_structural.md, gpu_native_crowd_input): build the attribute forms of the own crowd's vertex shaders.

For own_crowd_{match,entrance,card}.vert the variant is compiled with -DCROWD_VERTEX_INPUT into src\\scene\\spirv\\<name>_vi_vert.h (array <name>_vi_vert_spv): the member mesh and the members come from
vertex attributes (binding 0 and instance-rate binding 1 of the own crowd's ring), the index is gl_VertexIndex as it is. Plain glslang output, as the storage form's: the maths stays the same module for
module. The multiview forms (<name>_mv_vi_vert.h) come from tools\\shaders\\build_multiview_ps.py.

Every form (the three here and the three multiview ones, when they exist) is then checked: a clean spirv-val, no StorageBuffer or BufferBlock variable, no OpArrayLength, and exactly the input locations
of SDK vertex_input_layout.h's rule for its vi (mesh 2 uvec4 + members 3 uvec4; the cards 1 + 3).

    py tools\\shaders\\build_own_crowd_vi.py [--check]     --check: no build, only the checks
"""
import glob, os, re, shutil, subprocess, sys, tempfile

R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SCENE = os.path.join(R, 'src', 'scene')
SPV = os.path.join(SCENE, 'spirv')
NAMES = {'own_crowd_match': 5, 'own_crowd_entrance': 5, 'own_crowd_card': 4}


def sdk_tool(name):
    c = sorted(glob.glob(r'C:\VulkanSDK\*\Bin\%s.exe' % name), reverse=True)
    if c:
        return c[0]
    p = shutil.which(name)
    if p:
        return p
    raise SystemExit('%s not found (Vulkan SDK)' % name)


def header(data, name):
    words = ['0x%08X' % int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
    lines = ['    ' + ', '.join(words[i:i + 8]) + ',' for i in range(0, len(words), 8)]
    head = ['#pragma once',
            '// Session 95 (P7): the attribute form of ../%s.vert, generated by tools/shaders/build_own_crowd_vi.py' % name,
            '// (glslangValidator -V --target-env vulkan1.0 -DCROWD_VERTEX_INPUT -S vert). Do not edit: edit the source and run the script.',
            '#include <cstdint>', '', 'inline constexpr uint32_t %s_vi_vert_spv[] = {' % name] + lines + ['};', '']
    return '\r\n'.join(head)


def words_of(path):
    text = open(path, encoding='utf-8').read()
    body = text[text.index('= {'):]
    return b''.join(int(w, 16).to_bytes(4, 'little') for w in re.findall(r'0x[0-9A-Fa-f]{8}', body))


def check(path, locations, env, tmp):
    spv = os.path.join(tmp, os.path.basename(path) + '.spv')
    open(spv, 'wb').write(words_of(path))
    problems = []
    r = subprocess.run([sdk_tool('spirv-val'), '--target-env', env, spv], capture_output=True, text=True)
    if r.returncode:
        problems.append('spirv-val: ' + (r.stdout + r.stderr).strip()[:200])
    dis = subprocess.run([sdk_tool('spirv-dis'), spv], capture_output=True, text=True).stdout
    if 'StorageBuffer' in dis or 'BufferBlock' in dis:
        problems.append('a storage variable')
    if 'OpArrayLength' in dis:
        problems.append('OpArrayLength')
    inputs = set(re.findall(r'(%\w+) = OpVariable %\w+ Input', dis))
    found = sorted(int(m.group(2)) for m in re.finditer(r'OpDecorate (%\w+) Location (\d+)', dis) if m.group(1) in inputs)
    if found != list(range(locations)):
        problems.append('input locations %s, want 0-%d' % (found, locations - 1))
    return problems


def main():
    only_check = '--check' in sys.argv
    tmp = tempfile.mkdtemp(prefix='s95crowdvi_')
    bad = 0
    try:
        if not only_check:
            glslang = sdk_tool('glslangValidator')
            for name in NAMES:
                spv = os.path.join(tmp, name + '.spv')
                r = subprocess.run([glslang, '-V', '--target-env', 'vulkan1.0', '-DCROWD_VERTEX_INPUT', '-S', 'vert', '-o', spv, os.path.join(SCENE, name + '.vert')], capture_output=True, text=True)
                if r.returncode:
                    raise SystemExit('%s: glslang: %s' % (name, (r.stdout + r.stderr).strip()))
                open(os.path.join(SPV, name + '_vi_vert.h'), 'w', encoding='utf-8', newline='').write(header(open(spv, 'rb').read(), name))
                print('%s_vi_vert.h: %d words' % (name, os.path.getsize(spv) // 4))
        for name, locations in NAMES.items():
            for suffix, env in (('_vi_vert', 'vulkan1.0'), ('_mv_vi_vert', 'vulkan1.1')):
                path = os.path.join(SPV, name + suffix + '.h')
                if not os.path.exists(path):
                    print('%s%s.h: MISSING' % (name, suffix))
                    bad += 1
                    continue
                problems = check(path, locations, env, tmp)
                if problems:
                    bad += 1
                    print('%s%s: FAIL %s' % (name, suffix, '; '.join(problems)))
                else:
                    print('%s%s: ok' % (name, suffix))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
