"""Session 94 (gpu_native_instance_world): build the INSTANCING variants of our arena vertex shaders.

For each src\\scene\\arena_vs_*.vert a copy is made in a temp dir (next to copies of the .glsl includes) with
  - every  fc.c[N]  rewritten to  fc.c[XE_I + N],  XE_I = gl_InstanceIndex * XE_STRIDE
  - the constants block widened to 256 vec4 (the dynamic-offset descriptor's whole range, as the SDK's merged translations read it)
  - XE_STRIDE = a specialization constant (SpecId 0, int): the vec4s between two instances' constant blocks. The SDK patches its default with the
    translation's instanced_float_constants_stride (shader_swap.cpp BuildVertex); instance 0 reads at offset 0, so a run of one is the plain draw.
and compiled to src\\scene\\spirv\\<name>_inst_vert.h (array <name>_inst_vert_spv). The plain shaders and their headers are not touched.

    py tools\\shaders\\build_instanced_vs.py [name ...]
"""
import os, re, shutil, subprocess, sys, tempfile, glob

R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(R, 'src', 'scene')
OUT = os.path.join(SRC, 'spirv')

def find_glslang():
    c = sorted(glob.glob(r'C:\VulkanSDK\*\Bin\glslangValidator.exe'), reverse=True)
    if c:
        return c[0]
    p = shutil.which('glslangValidator')
    if p:
        return p
    raise SystemExit('glslangValidator not found (Vulkan SDK)')

def main():
    names = sys.argv[1:]
    glslang = find_glslang()
    tmp = tempfile.mkdtemp(prefix='s94inst_')
    try:
        for g in glob.glob(os.path.join(SRC, '*.glsl')):
            shutil.copy(g, tmp)
        for f in sorted(glob.glob(os.path.join(SRC, 'arena_vs_*.vert'))):
            base = os.path.splitext(os.path.basename(f))[0]
            if names and base not in names:
                continue
            text = open(f, encoding='utf-8').read()
            text, n1 = re.subn(r'fc\.c\[(\d+)\]', r'fc.c[XE_I + \1]', text)
            text, n2 = re.subn(r'vec4 c\[\d+\]', 'vec4 c[256]', text)
            inc = '#include "xenos_vs.glsl"'
            assert text.count(inc) == 1 and n1 and n2 == 1, (base, n1, n2)
            text = text.replace(inc, inc + '\n// Session 94 (gpu_native_instance_world): the instancing variant (tools/shaders/build_instanced_vs.py)\n'
                                'layout(constant_id = 0) const int XE_STRIDE = 8;\n#define XE_I (gl_InstanceIndex * XE_STRIDE)\n')
            tf = os.path.join(tmp, base + '.vert')
            open(tf, 'w', encoding='utf-8', newline='\n').write(text)
            spv = os.path.join(tmp, base + '.spv')
            r = subprocess.run([glslang, '-V', '--target-env', 'vulkan1.0', '-S', 'vert', '-o', spv, tf], capture_output=True, text=True)
            if r.returncode:
                print(r.stdout, r.stderr)
                raise SystemExit('glslangValidator failed on ' + base)
            data = open(spv, 'rb').read()
            words = ['0x%08X' % int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
            ident = base + '_inst_vert'
            lines = ['    ' + ', '.join(words[i:i + 8]) + ',' for i in range(0, len(words), 8)]
            header = ['#pragma once',
                      '// Session 94: the instancing variant of ../%s.vert, generated by tools\\shaders\\build_instanced_vs.py (every float constant read at' % base,
                      '// register + gl_InstanceIndex * XE_STRIDE; XE_STRIDE = specialization constant 0, default patched by the SDK). Do not edit: edit the .vert and run the script.',
                      '#include <cstdint>', '', 'inline constexpr uint32_t %s_spv[] = {' % ident] + lines + ['};', '']
            open(os.path.join(OUT, ident + '.h'), 'w', encoding='utf-8', newline='').write('\r\n'.join(header))
            print('%s: %d fc refs -> %s.h (%d words)' % (base, n1, ident, len(words)))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

main()
