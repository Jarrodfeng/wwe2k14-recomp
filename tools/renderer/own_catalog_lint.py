#!/usr/bin/env python3
"""S110 RDRPREP: keeps our own shader programs inside the pipeline store's shader catalog (0 game runs, a source scan).

The store can prebuild a stored pipeline only when the program behind its hash is in the shader catalog. The catalog holds the game-derived kVariants AND our own blobs
(rdr::fx::kOwnShaders, generated by compile_shaders.py from every src\\renderer\\shaders\\*.vert|*.frag, test_* left out), registered by ONE registrar
(src\\renderer_host\\pipeline_catalog.h RegisterShaderCatalogFrom). A new own program created outside that table would again be built on its first draw, mid-scene.
Rules:
  1. every `vertex_spirv` / `fragment_spirv` assignment in src\\** takes a kSpv_<x> that is a row of kOwnShaders (fx_spv_data.cpp), a kVariants entry's / a Variant object's
     .spirv, nullptr (each arm of a `c ? a : b`), or is one of the exemptions below (each with its reason); anything else (a hand-built array, another generator, the .spirv of
     a struct that is not a Variant) fails. A ProgramDesc made by a positional brace list (`ProgramDesc d{"n", words, ...}`, `AddProgram({...})`) fails too: its blobs are not
     named, so this rule could not read them.
  2. no src file but the registrar calls RegisterShaderCatalog( on a renderer (the one registrar is the only walker).
  3. scene_host.cpp, binder.h and tools\\scene\\frame_rig.cpp call RegisterShaderCatalogFrom with kVariants AND kOwnShaders; the registrar walks both ranges and hands them over in ONE call;
     binder.h keeps no loop of its own.
Planted twins (on the text in memory): (a) a kOwnShaders row dropped, (b) a fake kSpv site, (c) binder.h keeping its own kVariants-only loop, (d) the registrar without the own range.
  py -I tools\\renderer\\own_catalog_lint.py [--root DIR] [--plant]
Exit 0 = pass, 1 = fail."""
import argparse
import os
import re
import sys

ROWS_FILE = 'src/renderer/shaders/spv/fx_spv_data.cpp'
REGISTRAR = 'src/renderer_host/pipeline_catalog.h'
CALLERS = ('src/renderer_host/scene_host.cpp', 'src/renderer_adapter/binder.h', 'tools/scene/frame_rig.cpp')

# (file basename, RHS regex) -> reason. A site outside the own table that is NOT a program of ours made at run time.
EXEMPT = (
    ('renderer.cpp', r'[fv]blob\.words', 'PrebuildOne: the program is made from the CATALOG blob itself (the catalog is the source)'),
    ('front_end.cpp', r'w->data\(\)', 'the dev reload override (fview): a shader the developer swapped in at run time'),
    ('rplay.cpp', r'kSpv_test_\w+', 'the player tool\'s own test shaders (test_*: never in a game build)'),
    ('stencil_selftest.inc', r'kSpv_test_\w+', 'the stencil selftest\'s test shaders (test_*)'),
)
ASSIGN = re.compile(r'\b(?:vertex|fragment)_spirv\s*=(?!=)\s*([^,;]+)')
BRACE_PROGRAM = re.compile(r'(?<!struct )\bProgramDesc(?:\s+\w+)?\s*=?\s*\{\s*(?![.}])|\bAddProgram(?:Checked)?\(\s*(?:rdr::)?(?:ProgramDesc)?\s*\{\s*(?![.}])')   # S110 RDRPREP review
VARIANT_DECL = re.compile(r'\bVariant\s*(?:const\s*)?[&*]?\s*(\w+)\b(?!\s*\()')   # a name declared as an rdr::fx::Variant (a reference, a pointer, a range-for variable)


def rhs_ok(rhs, rows, variants):
    """S110 RDRPREP review: True when every blob the right-hand side can give is a kOwnShaders row, a kVariants entry's or a Variant object's .spirv / .spirv_alpha, or
    nullptr (the condition of a `c ? a : b` is left out). Any other name left over is a blob from outside the two tables."""
    rest = rhs.split('?', 1)[1] if '?' in rhs else rhs
    rest = re.sub(r'\bkSpv_(\w+)', lambda m: ' ' if m.group(1) in rows else m.group(0), rest)
    rest = re.sub(r'(?:\b(?:rdr::)?(?:fx::)?kVariants\s*\[[^\]]*\]|\b(\w+))\s*\.\s*spirv(?:_alpha)?\b', lambda m: ' ' if m.group(1) is None or m.group(1) in variants else m.group(0), rest)
    rest = re.sub(r'\bnullptr\b', ' ', rest)
    return re.fullmatch(r'[\s:()]*', rest) is not None


def read(root, rel):
    with open(os.path.join(root, *rel.split('/')), encoding='utf-8', errors='replace') as f:
        return f.read().replace('\r\n', '\n')


def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    return re.sub(r'//[^\n]*', '', s)


def own_rows(unit):
    """The names of the kOwnShaders rows in fx_spv_data.cpp."""
    m = re.search(r'kOwnShaders\[\d+\]\s*=\s*\{(.*?)\n\};', unit, flags=re.S)
    return set(re.findall(r'\{"(\w+)",\s*::kSpv_\1\b', m.group(1))) if m else set()


def rule1(sources, rows):
    """sources: {relpath: text}. Returns the offending sites."""
    bad = []
    for rel, text in sorted(sources.items()):
        base = rel.rsplit('/', 1)[-1]
        code = strip_comments(text)
        variants = set(VARIANT_DECL.findall(code))
        for m in ASSIGN.finditer(code):
            rhs = m.group(1).strip()
            if rhs_ok(rhs, rows, variants):
                continue
            if any(base == b and re.fullmatch(rx, rhs) for b, rx, _ in EXEMPT):
                continue
            bad.append('%s: %s_spirv = %s' % (rel, 'vertex' if 'vertex' in m.group(0) else 'fragment', rhs))
        for m in BRACE_PROGRAM.finditer(code):
            bad.append('%s: a program made by a positional brace list (%s...): name its blobs with vertex_spirv = / fragment_spirv =' % (rel, code[m.start():m.end() + 24].strip()))
    return bad


def rule2(sources):
    return ['%s calls RegisterShaderCatalog( itself' % rel for rel, t in sorted(sources.items())
            if rel != REGISTRAR and re.search(r'(?:\.|->)RegisterShaderCatalog\(', strip_comments(t)) and not rel.startswith('src/renderer/')]


def rule3(texts):
    """texts: {relpath: text} of the registrar and its three callers."""
    bad = []
    reg = strip_comments(texts.get(REGISTRAR, ''))
    if len(re.findall(r'\.RegisterShaderCatalog\(', reg)) != 1:
        bad.append('the registrar does not hand over in ONE RegisterShaderCatalog call')
    if not re.search(r'for\s*\(\s*It\s+\w+\s*=\s*first\s*;\s*\w+\s*!=\s*last', reg):
        bad.append('the registrar does not walk the kVariants range')
    if not re.search(r'for\s*\(\s*Ot\s+\w+\s*=\s*own_first\s*;\s*\w+\s*!=\s*own_last\s*;[^)]*\)\s*blobs\.push_back', reg):
        bad.append('the registrar does not walk the own range (kOwnShaders)')
    for rel in CALLERS:
        t = strip_comments(texts.get(rel, ''))
        c = re.search(r'RegisterShaderCatalogFrom\([^;]*;', t)
        if not c or 'kVariants' not in c.group(0) or 'kOwnShaders' not in c.group(0):
            bad.append('%s does not call RegisterShaderCatalogFrom with kVariants and kOwnShaders' % rel)
    b = strip_comments(texts.get('src/renderer_adapter/binder.h', ''))
    if re.search(r'RegisterShaderCatalog\(', b) or 'ShaderBlobDesc' in b:
        bad.append('src/renderer_adapter/binder.h keeps a catalog loop of its own')
    return bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', default=os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')))
    ap.add_argument('--plant', action='store_true')
    a = ap.parse_args()
    root = os.path.abspath(a.root)
    fails = []

    def say(ok, msg):
        print(('ok   ' if ok else 'FAIL ') + msg)
        if not ok:
            fails.append(msg)

    sources = {}
    for r, ds, fs in os.walk(os.path.join(root, 'src')):
        ds[:] = [d for d in ds if d not in ('out', 'node_modules', '.git')]
        for f in fs:
            if f.endswith(('.cpp', '.h', '.inc', '.hpp')):
                rel = os.path.relpath(os.path.join(r, f), root).replace('\\', '/')
                if rel.startswith('src/renderer/shaders/spv/'):
                    continue
                sources[rel] = read(root, rel)
    unit = read(root, ROWS_FILE)
    rows = own_rows(unit)
    headers = {f[:-2] for f in os.listdir(os.path.join(root, 'src', 'renderer', 'shaders', 'spv')) if f.startswith('rdr_') and f.endswith(('_vert.h', '_frag.h'))}
    say(bool(rows) and rows == headers, 'kOwnShaders holds one row per own rdr_* shader header (%d rows, %d headers; differ: %s)' % (len(rows), len(headers), sorted(rows ^ headers)[:3] or 'none'))
    bad1 = rule1(sources, rows)
    say(not bad1, 'rule 1: every vertex_spirv / fragment_spirv assignment is a kOwnShaders row, a kVariants entry or an exemption (offenders: %s)' % (bad1[:4] or 'none'))
    bad2 = rule2(sources)
    say(not bad2, 'rule 2: only the registrar calls RegisterShaderCatalog (offenders: %s)' % (bad2[:3] or 'none'))
    texts = {rel: (sources[rel] if rel in sources else read(root, rel)) for rel in (REGISTRAR,) + CALLERS}
    bad3 = rule3(texts)
    say(not bad3, 'rule 3: scene_host, binder and frame_rig call the one registrar with both ranges; it walks both (offenders: %s)' % (bad3[:3] or 'none'))

    if a.plant:
        victim = 'rdr_flash_frag'
        say(victim in rows and bool(rule1(sources, rows - {victim})), 'planted twin (a) (the kOwnShaders row %s dropped) is caught by rule 1' % victim)
        fake = dict(sources)
        fake['src/renderer_scene/post_pass.cpp'] = fake['src/renderer_scene/post_pass.cpp'] + '\nvoid F() { rdr::ProgramDesc pd; pd.fragment_spirv = kSpv_rdr_new_frag; }\n'
        say(bool(rule1(fake, rows)), 'planted twin (b) (a fake pd.fragment_spirv = kSpv_rdr_new_frag; site) is caught by rule 1')
        hand = dict(sources)
        hand['src/renderer_scene/post_pass.cpp'] = hand['src/renderer_scene/post_pass.cpp'] + '\nstatic const uint32_t kMine[] = {1}; void G() { rdr::ProgramDesc pd; pd.vertex_spirv = kMine; }\n'
        say(bool(rule1(hand, rows)), 'planted twin (b2) (a hand-built array site) is caught by rule 1')
        # S110 RDRPREP review: the ways past rule 1's `x_spirv = kSpv_*` reading (a program made without that assignment, or a non-variant `.spirv`, or a mixed right-hand side)
        for tag, site in (('b3', 'static const uint32_t kMine[] = {1}; void G() { rdr::ProgramDesc d{"rdr_new", kMine, sizeof(kMine), nullptr, 0}; }'),
                          ('b4', 'static const uint32_t kMine[] = {1}; void G(rdr::Renderer& r) { r.AddProgram({"rdr_new", kMine, sizeof(kMine)}); }'),
                          ('b5', 'struct Blob { const uint32_t* spirv; }; static const uint32_t kMine[] = {1}; static const Blob kB{kMine}; void G() { rdr::ProgramDesc pd; pd.vertex_spirv = kB.spirv; }'),
                          ('b6', 'static const uint32_t kMine[] = {1}; void G(bool alt) { rdr::ProgramDesc pd; pd.fragment_spirv = alt ? kMine : rdr::fx::kVariants[0].spirv; }')):
            fake = dict(sources)
            fake['src/renderer_scene/post_pass.cpp'] = fake['src/renderer_scene/post_pass.cpp'] + '\n' + site + '\n'
            say(bool(rule1(fake, rows)), 'planted twin (%s) (%s) is caught by rule 1' % (tag, site[site.index('void G'):][:90]))
        t = dict(texts)
        t['src/renderer_adapter/binder.h'] = t['src/renderer_adapter/binder.h'] + ('\n  void RegisterOld() { std::vector<rdr::Renderer::ShaderBlobDesc> blobs;\n'
                                                                                  '    for (const rdr::fx::Variant& v : rdr::fx::kVariants) blobs.push_back({v.name, v.spirv, v.bytes});\n'
                                                                                  '    renderer_.RegisterShaderCatalog(blobs.data(), blobs.size()); }\n')
        say(bool(rule3(t)), 'planted twin (c) (binder.h keeping its own kVariants-only loop) is caught by rule 3')
        s2 = dict(sources)
        s2['src/renderer_adapter/binder.h'] = t['src/renderer_adapter/binder.h']
        say(bool(rule2(s2)), 'planted twin (c2) (binder.h calling RegisterShaderCatalog itself) is caught by rule 2')
        t = dict(texts)
        t[REGISTRAR] = re.sub(r'for \(Ot o = own_first; o != own_last; \+\+o\) blobs\.push_back\([^;]*;', '', t[REGISTRAR])
        say(t[REGISTRAR] != texts[REGISTRAR] and bool(rule3(t)), 'planted twin (d) (the registrar without the own range) is caught by rule 3')
    print('own_catalog_lint: ' + ('FAILED (%d)' % len(fails) if fails else 'every check passed'))
    return 1 if fails else 0


if __name__ == '__main__':
    sys.exit(main())
